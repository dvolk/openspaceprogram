#!/usr/bin/env python3
"""The gates that cost no compiler: file hygiene, size, JSON parseability, secrets.

Why a script in utils/ rather than four lines in .gitea/workflows/: a check that only
exists in a workflow rots. It cannot be reproduced by whoever it just failed, it does not
run on a laptop mid-task, and nobody defends a rule they have never seen fire locally.
So CI calls this file, and `make lint` calls this file, and the rule is one thing.

Why these four and not a C++ linter: the CI runner we have is a small box, and the
middleware submodules alone are 590 MB (bullet3 347 MB, assimp 243 MB) -- a gate that
compiles does not fit it. Nothing here compiles a translation unit, and nothing here
needs a third-party python module: every gate is stdlib and the whole set runs in about a
second, which is what makes it worth running on every push.

WHAT HYGIENE IS NOT ASKED OF, because a gate that yells about other people's bytes gets
turned off. After the baseline was cleaned, 758 trailing-whitespace lines remain outside
middleware/: 751 in utils/rss/ (scraped third-party HTML -- their whitespace, not ours)
and 7 under reports/, which are immutable snapshots (QWEN.md). e2e/fixtures/ are
byte-pinned inputs, some deliberately malformed (save_bad_format/save.json), where a
missing final newline may be part of the pin.

That skip list is HYGIENE only. The secret scan runs on every tracked text file, the
scraped and pinned trees included -- those are exactly where a credential gets pasted: a
worklog under reports/, a fixture under e2e/fixtures/. An earlier draft `continue`d past
the skip list and lost the secret scan with it, while its comment promised the opposite;
--self-test now pins the split, because a gate that reports "0 secret findings" for a tree
it never opened is indistinguishable from a clean tree.

Hygiene asks nothing about extensions -- a NUL sniff decides text vs binary -- because an
extension allow-list is where a gate stops seeing things: it found a trailing space in
res/shaders/skyboxShader.vs and tabs in utils/debian/rules, neither of which a list would
have looked at. A tab is SYNTAX in exactly three tracked files, named by full path.

Baselines as this gate was written: hygiene clean; 0 CRLF; 0 secret hits; biggest tracked
file outside middleware 7.0 MB (res/heightmaps/earth/earth_hm.i16) against a 20 MB cap;
every tracked res/**/*.json parses strictly (no NaN/Infinity -- see below).

A file that is not UTF-8 text is a HOLE, not a skip, so it is reported rather than
shrugged off: a res/**/*.json saved as UTF-16 by a Windows editor, or carrying an embedded
NUL, is exactly the shape that makes nlohmann answer half a system at runtime. A file with
a UTF-16 byte-order mark is decoded and scanned as the text it is; anything else binary
(57 tracked files today, all genuinely so: png, ico, ttf, i16, pdf, gz) sees the size gate
and nothing else, which is why the count of files is printed with every verdict.

The JSON gate is RFC-strict, not Python-strict: json.loads accepts NaN and Infinity, the
corpus is generated by Python (json.dumps writes them without being told not to), and
nlohmann's lexer has no case for them. So a NaN in res/systems is green here and a broken
system in the game; the gate rejects the constant instead.

The secret gate is a hairwire, not an audit: credential SHAPES (a labelled assignment, a
key block, a provider token shape, an env assignment whose name says secret) so the thing
that stops a leak is a commit rather than a rotation drill afterwards. It never prints the
matched text -- the finding is file and line, because a log that echoes the secret has put
the secret somewhere new. Tuning it against this repo, not against imagination: the first
version called `passwd = getpwuid(getuid())` a credential; the second called
`token = token.replace(...)` one, because a bare `{12,}` backtracks to exactly twelve
characters; the third called `token = user.auth_token` one, because the run class accepted
a dot. All three are pinned in --self-test as must-stay-quiet, alongside must-fire fixtures
that are assembled at runtime -- this file is scanned too, and a gate whose own source
trips it turns every future push red. A gate that cries wolf on ordinary code is a gate
that gets muted.
"""

import argparse
import bisect
import errno
import json
import os
import re
import subprocess
import sys

# Hygiene only -- see the docstring: the secret scan ignores this list. Entries are named
# as they appear in `git ls-files`, so anything not tracked (dist/, build/) does not need
# listing -- and if someone ever does track build output, the size gate and hygiene should
# both see it.
HYGIENE_SKIP = ("middleware/", "reports/", "utils/rss/", "e2e/fixtures/", "staging/")
# Full paths, not basenames: a basename match would exempt every file named `rules` that
# anyone ever adds.
TAB_OK = {"Makefile", ".gitmodules", "utils/debian/rules"}

# 20 MB is ~3x the largest file we ship today, so it catches "I committed a video / a
# build artefact / a 300 MB mesh export" -- the kind of thing that quietly doubles what
# every clone costs. An over-cap file is reported and NOT read: slurping the thing we just
# called too big is how a 2 GB mistake turns into an OOM instead of one clean line.
MAX_BYTES = 20 * 1024 * 1024

# Five shapes, each checked against the real lines in this repo, because every rule that
# cries wolf on ordinary code gets muted:
#  - labelled credential, bare value: a credential WORD then `:`/`=` then a 12+ char run.
#    The run ends at a boundary the class knows, NOT at `(?!\()` -- a bare `{12,}` backtracks
#    to exactly twelve characters and calls `token = token.replace(...)` a credential. The
#    class holds no dot for the same reason: `token = user.auth_token` is ordinary code, and
#    no credential in this tree is spelled with dots.
#  - quoted credential: a NAME containing a credential word (underscore-padded counts, which
#    `\b` alone cannot see) then a quoted value of 12+. This is the rule that sees JSON, where
#    a quote sits between the key and the colon, and a quoted secret is a literal, so the
#    value may hold any punctuation. The 12 floor is what keeps `password: "…"` placeholders
#    in a worklog quiet.
#  - env-style: an assignment whose NAME says secret, with a 16+ bare value that contains a
#    digit. The digit is the difference between a key and `APP_SECRET_HEADER = internal_name`,
#    and the trailing boundary stops the backtrack that made the previous two rules lie.
#  - a key block: PEM or PGP.
#  - provider token shapes (GitHub / AWS key id / Slack / GitLab) in ONE alternation: three
#    separate passes over 21 MB cost ~2 s on the CI box, one costs ~0.25 s. The finding is the
#    file and line either way; which provider it was is visible there.
# That is why the self-test's fixtures are assembled at runtime: this file is scanned too.
SECRET_PATTERNS = [
    ("labelled credential",
     re.compile(r"(?i)\b(api[_ -]?key|apikey|secret[_ -]?key|access[_ -]?token|auth[_ -]?token"
                r"|private[_ -]?key|password|passwd|secret|token)\b"
                r"\s*[:=]\s*[A-Za-z0-9\-_+=/]{12,}(?![A-Za-z0-9\-_+=/(])")),
    ("quoted credential",
     re.compile(r"(?i)\b[a-z0-9_]*(?:secret|api_?key|access[_ -]?key|auth[_ -]?token|token|passwd|password|credential)"
                r"[a-z0-9_]*['\"\\]*\s*[:=]\s*\\?['\"][^\s'\"]{12,}")),
    ("env-style secret assignment",
     re.compile(r"(?im)^[ \t]*(?:export[ \t]+)?[A-Z0-9_]*"
                r"(?:SECRET|API_?KEY|ACCESS_KEY|AUTH_TOKEN|PASSWORD|PASSWD|CREDENTIAL)[A-Z0-9_]*"
                r"[ \t]*[:=][ \t]*(?=[A-Za-z0-9/+_\-]*[0-9])(?=[A-Za-z0-9/+_\-]{16,})"
                r"[A-Za-z0-9/+_\-]{16,}(?![A-Za-z0-9/+_\-])")),
    ("private key block", re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY( BLOCK)?-----")),
    ("provider token shape",
     re.compile(r"\bgh[pousr]_[A-Za-z0-9]{20,}\b|\bgithub_pat_[A-Za-z0-9_]{20,}\b"
                r"|\bAKIA[0-9A-Z]{16}\b|\bxox[baprs]-[A-Za-z0-9-]{10,}\b"
                r"|\bglpat-[A-Za-z0-9_\-]{20,}\b")),
]

MAX_HYGIENE_REPORT = 30
MAX_OTHER_REPORT = 100


def git(args):
    """Run git, or exit 2 loudly. A gate that dies with a traceback at the top of the log is
    a gate someone disables; exit 2 also separates "the gate broke" from "the gate found
    something" (1), which the workflow's log can be read for."""
    try:
        return subprocess.run(["git"] + args, check=True, capture_output=True)
    except (OSError, subprocess.CalledProcessError) as e:
        print("ci_lint: git unavailable, so NOTHING was scanned: %s" % e)
        sys.exit(2)


def index_lists(raw):
    """(files, submodules) from `git ls-files -z -s` output bytes.

    -z for two reasons: paths arrive unquoted (a C-quoted name like '"caf\\xc3\\xa9.txt"'
    cannot be stat'd, and an un-stat'able file used to skip every gate and still count as
    scanned) and it is correct for names containing newlines or tabs. -s so submodule
    gitlinks are recognised by mode 160000 instead of by the accident of open() failing,
    and so a conflicted path -- which git lists once per merge stage -- is scanned once
    (lowest stage) instead of reporting one leak three times.
    """
    best = {}
    for entry in raw.split(b"\0"):
        if not entry:
            continue
        meta, _, name = entry.partition(b"\t")
        fields = meta.split(b" ")
        if len(fields) < 3:
            continue
        mode, stage = fields[0], fields[2]
        path = os.fsdecode(name)
        try:
            stage = int(stage)
        except ValueError:
            stage = 0
        kind = "sub" if mode == b"160000" else "file"
        held = best.get(path)
        if held is None or stage < held[0]:
            best[path] = (stage, kind)
    files = [p for p, (_, kind) in best.items() if kind == "file"]
    subs = [p for p, (_, kind) in best.items() if kind == "sub"]
    return files, subs


def tracked_files():
    return index_lists(git(["ls-files", "-z", "-s"]).stdout)


def read_text(path):
    """The file as text, or None when it really is binary.

    A UTF-16 BOM means TEXT -- an editor on Windows wrote it -- so decode it and let the
    gates see it. The NUL sniff alone would blind the secret gate to exactly the worklog it
    exists to read, and the JSON gate to a res/systems file the loader cannot parse.
    """
    with open(path, "rb") as fh:
        blob = fh.read()
    if blob[:2] in (b"\xff\xfe", b"\xfe\xff"):
        return blob.decode("utf-16", errors="replace")
    if b"\0" in blob[:8192]:
        return None
    return blob.decode("utf-8", errors="replace")


def hygiene_applies(path):
    return not path.startswith(HYGIENE_SKIP)


def size_finding(name, nbytes):
    if nbytes > MAX_BYTES:
        return ("size: %s is %.1f MB, over the %d MB cap"
                % (name, nbytes / (1024 * 1024), MAX_BYTES // (1024 * 1024)))
    return None


def hygiene_findings(name, text):
    """Tabs (outside TAB_OK), trailing whitespace, CR, missing final newline."""
    out = []
    allow_tabs = name in TAB_OK
    for i, line in enumerate(text.split("\n"), start=1):
        # Strip a trailing CR before the trailing-whitespace test so a CRLF file reports
        # the carriage return once, not CR plus "trailing whitespace" on every line.
        bare = line[:-1] if line.endswith("\r") else line
        if "\r" in line:
            out.append((i, "carriage return (CRLF line ending)"))
        if bare.endswith((" ", "\t")):
            out.append((i, "trailing whitespace"))
        if not allow_tabs and "\t" in bare:
            out.append((i, "tab where indentation is spaces"))
    if text and not text.endswith("\n"):
        out.append((text.count("\n") + 1, "no final newline"))
    return out


def _line_starts(text):
    """Offsets where each line begins, so a hit position can become a line number."""
    starts = [0]
    i = 0
    while True:
        j = text.find("\n", i)
        if j < 0:
            return starts
        starts.append(j + 1)
        i = j + 1


def secret_findings(text):
    """(rule, line) per hit -- the match itself is never returned.

    Line numbers come from one index of line starts, bisected per hit. Counting newlines
    from the top of the file for every match is quadratic: on a scraped-page-sized file that
    trips a rule 37,000 times that cost 9.6 s against 0.23 s for the same file with no hits,
    and utils/rss/ is 21 MB of other people's HTML.
    """
    hits = [(rule, m.start())
            for rule, pat in SECRET_PATTERNS
            for m in pat.finditer(text)]
    if not hits:
        return []
    starts = _line_starts(text)
    return [(rule, bisect.bisect_right(starts, pos)) for rule, pos in hits]


def json_error(text):
    """Why this is not valid JSON, or None.

    Strict, not Python-strict: json.loads accepts NaN and Infinity, the generators that
    write this corpus are Python (json.dumps emits those constants unless told not to), and
    the loader that reads them at runtime is nlohmann, whose lexer has no case for them. So
    a NaN in res/systems would otherwise be a green gate and a half-built system in the game.
    """
    def reject(name):
        raise ValueError("non-standard constant " + name)

    try:
        json.loads(text, parse_constant=reject)
    except ValueError as e:
        return str(e)
    return None


def scan_file(path, text, finds):
    """The three content gates over one already-read file.

    Split out of the loop so --self-test can pin the WIRING, not just the predicates: the
    #819 bug was a `continue` sitting above the secret scan, and no predicate test can see
    that. Hygiene is scoped by HYGIENE_SKIP, the rest is unconditional -- a skip list is
    about whitespace, never about leaks.
    """
    name = show_path(path)
    if path.startswith("res/") and path.endswith(".json"):
        err = json_error(text)
        if err is not None:
            finds["json"].append("json: %s does not parse: %s" % (name, err))
    if hygiene_applies(path):
        for line, why in hygiene_findings(path, text):
            finds["hygiene"].append("hygiene: %s:%d %s" % (name, line, why))
    for rule, line in secret_findings(text):
        finds["secret"].append("secret: %s:%d %s" % (name, line, rule))


def show_path(path):
    """One finding must be one output line; a tracked name may contain a newline."""
    return path.replace("\n", "\\n").replace("\r", "\\r")


def unread_finding(path, err):
    if getattr(err, "errno", None) == errno.ENOENT:
        # The everyday shape of this (rm instead of git rm) should read as itself, not as a
        # permissions mystery.
        return "unread: %s (in the index, missing from the worktree)" % show_path(path)
    return "unread: %s (%s)" % (show_path(path), err.strerror or err)


def run_gates():
    """finds maps gate -> list of printable findings."""
    files, submodules = tracked_files()
    finds = {gate: [] for gate in ("hygiene", "size", "json", "secret", "unread")}

    for path in files:
        try:
            size = os.path.getsize(path)
        except OSError as e:
            # Never silent: an unreadable tracked path is a hole in every gate below.
            finds["unread"].append(unread_finding(path, e))
            continue
        big = size_finding(show_path(path), size)
        if big is not None:
            finds["size"].append(big)
            continue

        try:
            text = read_text(path)
        except OSError as e:
            finds["unread"].append(unread_finding(path, e))
            continue

        if text is None:
            # A res JSON that is not text is a finding, not a pass: an embedded NUL, or a
            # BOM the sniffer did not cover, is what the loader chokes on.
            if path.startswith("res/") and path.endswith(".json"):
                finds["json"].append("json: %s is not text (NUL in the first 8 KiB)"
                                     % show_path(path))
            continue

        scan_file(path, text, finds)

    return finds, len(files), len(submodules)


def self_test():
    """Every gate must fire on a planted string, or it is a gate in name only (#650's lesson)."""
    bad = []
    # (path, contents, the one hygiene finding it must produce -- None means stay clean)
    for name, text, want in [
        ("src/plant.cpp", "int x = 1;   \n", "trailing whitespace"),
        ("src/plant.cpp", "int x = 1;", "no final newline"),
        ("src/plant.cpp", "a\tb\n", "tab where indentation is spaces"),
        ("src/plant.cpp", "a\r\n", "carriage return (CRLF line ending)"),
        ("Makefile", "target:\n\tcmd\n", None),        # a tab in a recipe is syntax
        ("utils/debian/rules", "build:\n\techo hi\n", None),
    ]:
        got = [why for _, why in hygiene_findings(name, text)]
        if want is None:
            if got:
                bad.append("%s: tab exemption lost, saw %r" % (name, got))
        elif got != [want]:
            bad.append("%s: planted %r -> %r (want exactly that one finding)" % (name, want, got))

    # Secrets: assembled where writing the shape out whole would trip the scan (and the
    # scan runs on this file). A fixture that reads as `KEYWORD = "value"` with a 12+ value
    # in one contiguous run WILL be caught by its own gate, which is a good test of the
    # self-scan below but not something that can be committed.
    for text, want in [
        ("api" + "_key = hunter2hunter2x\n", "labelled credential"),
        ("pass" + "word: hunter2hunter2x\n", "labelled credential"),
        ('{"pass' + 'word": "hunter2hunter2"}\n', "quoted credential"),      # JSON key quoting
        ("token: \\" + '"supersecretvalue\\"' + "\n", "quoted credential"),   # escaped quotes
        ("MY_DB_PASSWORD " + '= "p@ssw0rd-for-the-demo"\n', "quoted credential"),
        ("-----BEGIN " + "RSA PRIVATE KEY-----\n", "private key block"),
        ("-----BEGIN " + "PGP PRIVATE KEY BLOCK-----\n", "private key block"),
        ("t = ghp_" + "A" * 36 + "\n", "provider token shape"),
        ("k = AKIA" + "A" * 16 + "\n", "provider token shape"),
        ("s = xoxb-" + "A" * 24 + "\n", "provider token shape"),
        ("GITLA" + "B_TOKEN = glpat-" + "B" * 24 + "\n", "provider token shape"),
        ("MY_APP_SECRET " + "= abcd1234efgh5678ijkl\n", "env-style secret assignment"),
        ("export " + "SERVICE_PASSWORD=hunter2hunter2hunter\n", "env-style secret assignment"),
    ]:
        got = [rule for rule, _ in secret_findings(text)]
        if want not in got:
            bad.append("secret gate missed %r (saw %r)" % (want, got))
    # ... and must NOT fire on ordinary code. Most of these are lines that exist in this
    # repo, which is how the missed/wolf-ish balance got set: a bare `{12,}` followed by
    # `(?!\()` backtracks to exactly 12 characters and calls `token = token.replace(...)` a
    # credential; a run class that accepts a dot calls `token = user.auth_token` one; a
    # 6-character quoted floor calls a docs placeholder `password: "…"` one; and an
    # env-style rule with no digit-or-boundary on its value calls `APP_SECRET_HEADER =
    # internal_header_name` -- ordinary module config -- one.
    for text in ["passwd = getpwuid(getuid());\n", "cfg.api_key = load_key();\n",
                 "const char *password = prompt();\n", "token: optional field\n",
                 'token = token.replace("\\\\", "")\n',
                 'token = os.environ.get("TEAWRAP_' + 'TOKEN")\n',
                 "token = user.auth_token\n", "secret = self.settings_registry\n",
                 'password: "string"\n', "password = \"required\"\n",
                 "APP_SECRET_HEADER = internal_header_name\n",
                 "GITHUB_TOKEN = os.environ['GITHUB_TOKEN']\n"]:
        got = secret_findings(text)
        if got:
            bad.append("secret gate false-positive on %r -> %r" % (text, got))

    # The skip list is hygiene-only -- and pinned through scan_file, the loop body, not just
    # through the hygiene_applies predicate. The #819 bug was a `continue` above the secret
    # scan, and a predicate test cannot see a missing call: pinning only the predicate let
    # the reintroduced bug keep printing "self-test ok".
    leak = 'pass' + "word = hunter2hunter2x\n"
    for path in ("reports/x/y.md", "utils/rss/z.html", "e2e/fixtures/save_bad_format/save.json",
                 "src/gameui.cpp", "utils/ci_lint.py"):
        f = {g: [] for g in ("hygiene", "size", "json", "secret", "unread")}
        scan_file(path, leak, f)
        if len(f["secret"]) != 1:
            bad.append("scan_file lost the planted credential in %s -> %r" % (path, f["secret"]))
    for path, want in [("reports/x/y.md", 0), ("utils/rss/z.html", 0),
                       ("e2e/fixtures/save_bad_format/save.json", 0),
                       ("src/gameui.cpp", 1), ("utils/ci_lint.py", 1)]:
        f = {g: [] for g in ("hygiene", "size", "json", "secret", "unread")}
        scan_file(path, "int x = 1;   \n", f)
        if len(f["hygiene"]) != want:
            bad.append("scan_file hygiene scope wrong for %s -> %r" % (path, f["hygiene"]))

    # The json gate belongs to res/ and nowhere else, and it is strict about what parses.
    f = {g: [] for g in ("hygiene", "size", "json", "secret", "unread")}
    scan_file("res/systems/probe.json", '{"a": }', f)
    if len(f["json"]) != 1:
        bad.append("scan_file missed broken res JSON -> %r" % f["json"])
    f = {g: [] for g in ("hygiene", "size", "json", "secret", "unread")}
    scan_file("src/probe.cpp", '{"albedo": NaN}', f)
    if f["json"]:
        bad.append("scan_file ran the json gate outside res/ -> %r" % f["json"])

    # Index parsing: gitlinks out (by mode, not by open() failing), a conflicted path once
    # rather than once per stage, and names that contain a tab or non-ASCII intact.
    raw = (b"100644 aaa 0\tok.txt\x00"
           b"160000 bbb 0\tmiddleware/bullet3\x00"
           b"100644 c1 1\tconf.txt\x00100644 c2 2\tconf.txt\x00"
           b"100644 ddd 0\tcaf\xc3\xa9\tw.txt\x00"
           b"120000 eee 0\tsymlink.txt\x00")
    got_files, got_subs = index_lists(raw)
    if got_subs != ["middleware/bullet3"]:
        bad.append("index_lists lost a gitlink -> %r" % (got_subs,))
    if got_files.count("conf.txt") != 1:
        bad.append("index_lists scanned a conflicted path %d times" % got_files.count("conf.txt"))
    if "café\tw.txt" not in got_files or "ok.txt" not in got_files or "symlink.txt" not in got_files:
        bad.append("index_lists mangled a name -> %r" % (got_files,))

    # And this file itself must pass the gates that apply to it: every pattern lives here,
    # so a fixture or a pattern that trips its own scan turns every future push red -- and
    # this file is hygiene-scoped, so a stray trailing space here does the same.
    try:
        with open(os.path.realpath(__file__), encoding="utf-8", errors="replace") as fh:
            own = fh.read()
    except OSError as e:                     # only reachable if run outside a checkout
        bad.append("could not re-read %s: %s" % (__file__, e))
    else:
        hits = secret_findings(own)
        if hits:
            bad.append("ci_lint.py trips its own secret gate: %s"
                       % ", ".join("%s at line %d" % (rule, line) for rule, line in hits))
        dirt = hygiene_findings("utils/ci_lint.py", own)
        if dirt:
            bad.append("ci_lint.py trips its own hygiene gate: %s"
                       % ", ".join("line %d %s" % (line, why) for line, why in dirt[:5]))

    for text, must_fail in [("{\"a\": }", True), ("{\"a\": 1}", False),
                            ("{\"a\": NaN}", True), ("{\"a\": -Infinity}", True)]:
        if (json_error(text) is not None) != must_fail:
            bad.append("json gate wrong on %r" % text)

    over, under = MAX_BYTES + 1, MAX_BYTES - 1
    if size_finding("res/plant.bin", over) is None or size_finding("res/plant.bin", under) is not None:
        bad.append("size gate wrong at the cap")

    if bad:
        print("ci_lint SELF-TEST FAILED:")
        for b in bad:
            print("   " + b)
        return 1
    print("ci_lint self-test ok: hygiene, size, json and secret gates each fire on a "
          "planted string; scan_file reaches every tree for leaks and only the scoped ones "
          "for hygiene; index parsing keeps gitlinks out and names intact; the tab "
          "exemptions hold; the secret gate stays quiet on ordinary code; this file passes "
          "its own gates")
    return 0


def print_gate(gate, items, cap):
    for f in items[:cap]:
        print(f)
    if len(items) > cap:
        print("%s: ... %d more not shown" % (gate, len(items) - cap))


def main():
    ap = argparse.ArgumentParser(description="No-compiler repo gates (CI runs this).")
    ap.add_argument("--self-test", action="store_true", help="check the gates fire, then exit")
    args = ap.parse_args()
    if args.self_test:
        return self_test()

    # A finding names a path, and a path may hold bytes the terminal cannot encode -- a
    # traceback in place of the verdict line is the worst possible output for a gate.
    try:
        sys.stdout.reconfigure(errors="backslashreplace")
    except (AttributeError, ValueError):
        pass

    # git ls-files is CWD-relative while every gate matches root-relative prefixes, so a
    # run from a subdirectory would scan part of the tree, drop the res/ gates and turn the
    # skip list into noise. Anchor on the toplevel.
    top = git(["rev-parse", "--show-toplevel"]).stdout.decode().strip()
    if top:
        os.chdir(top)

    finds, nfiles, nsub = run_gates()
    # Hygiene is capped because it is the one gate that can produce hundreds of lines of
    # near-duplicates. Size, json, secret and unread are capped far above what we ever see
    # so the reason a build broke is never cut off -- a global cap once buried the one
    # secret finding behind 30 hygiene lines.
    print_gate("hygiene", finds["hygiene"], MAX_HYGIENE_REPORT)
    for gate in ("size", "json", "secret", "unread"):
        print_gate(gate, finds[gate], MAX_OTHER_REPORT)
    total = sum(len(v) for v in finds.values())
    print("ci_lint: %d tracked files (%d submodules skipped) -- %d hygiene, %d size, "
          "%d json, %d secret, %d unread findings"
          % (nfiles, nsub, len(finds["hygiene"]), len(finds["size"]), len(finds["json"]),
             len(finds["secret"]), len(finds["unread"])))
    return 1 if total else 0


if __name__ == "__main__":
    sys.exit(main())
