#!/usr/bin/env python3
"""Generate a FUSELAGE .obj: a spindle (ogive nose, parallel midbody, boat-tail),
stack axis +Z, nose at +Z, flat per-face normals, CCW winding.

Why this exists (#490/#557): a light aeroplane built from the cylinder catalogue is
a stack of barrels -- capsule (Cd 0.35) + tank (1.0) + shroud (0.9) + wheel (1.1),
each billed on its own disc. One smooth body with a nose and a boat-tail is what a
fuselage is, and it is one part with one Cd instead of four with four. The profile
is the shape the Cd family assumes: no separation on the nose, a mild adverse
gradient over the tail, and a base sized for the engine that bolts onto it.

Same OBJ conventions as gen_nose_cap.py / gen_wing.py."""
import argparse
import math


def unit(v):
    L = math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2])
    return (v[0] / L, v[1] / L, v[2] / L) if L > 0 else (0.0, 0.0, 1.0)


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def face_normal(a, b, c):
    return unit(cross(sub(b, a), sub(c, a)))


def profile(r, h, nose_frac, tail_frac, base_frac, rings):
    """(z, radius) stations from the nose tip (+h/2) to the base (-h/2)."""
    z_nose = h / 2.0
    z_tail = z_nose - nose_frac * h
    z_base = -h / 2.0
    z_bt = z_base + tail_frac * h
    st = [(z_nose, 0.0)]
    for i in range(1, rings + 1):
        t = i / float(rings)
        z = z_nose - t * nose_frac * h
        st.append((z, r * math.sqrt(max(0.0, 1.0 - (1.0 - t) ** 2))))
    # the nose loop's last sample is ALREADY (z_tail, r): a second ring there would
    # be a zero-height band, which reads as a doubled edge to the watertight check.
    st.append((z_bt, r))
    for i in range(1, rings + 1):
        t = i / float(rings)
        st.append((z_bt - t * tail_frac * h, r * (1.0 - (1.0 - base_frac) * t)))
    return st


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("dst", help="destination .obj")
    ap.add_argument("--radius", type=float, default=1.0)
    ap.add_argument("--height", type=float, default=6.0)
    ap.add_argument("--segments", type=int, default=24)
    ap.add_argument("--rings", type=int, default=6,
                    help="samples on the nose and on the boat-tail")
    ap.add_argument("--nose-frac", type=float, default=0.28)
    ap.add_argument("--tail-frac", type=float, default=0.22)
    ap.add_argument("--base-frac", type=float, default=0.45)
    a = ap.parse_args()
    if a.radius <= 0 or a.height <= 0 or a.segments < 3 or a.rings < 1:
        ap.error("radius/height must be > 0, segments >= 3, rings >= 1")
    if not (0.0 < a.nose_frac and 0.0 < a.tail_frac
            and a.nose_frac + a.tail_frac < 1.0 and 0.0 < a.base_frac <= 1.0):
        ap.error("need 0 < nose_frac, 0 < tail_frac, nose+tail < 1, 0 < base_frac <= 1")

    r, h, n = a.radius, a.height, a.segments
    st = profile(r, h, a.nose_frac, a.tail_frac, a.base_frac, a.rings)

    pos = []
    ring_at = []
    for z, rad in st:
        ring_at.append(len(pos))
        if rad <= 1e-9:
            pos.append((0.0, 0.0, z))
        else:
            for i in range(n):
                th = 2.0 * math.pi * i / n
                pos.append((rad * math.cos(th), rad * math.sin(th), z))
    base_center = len(pos)
    pos.append((0.0, 0.0, st[-1][0]))

    faces = []   # [(i, j, k, outward_hint)] -- hint: +1 radial, -1 = -Z
    for k in range(len(st) - 1):
        A, B = ring_at[k], ring_at[k + 1]
        if st[k][1] <= 1e-9:                     # nose tip: fan
            for i in range(n):
                j = (i + 1) % n
                faces.append((A, B + i, B + j, +1))
        else:
            for i in range(n):
                j = (i + 1) % n
                faces.append((A + i, A + j, B + j, +1))
                faces.append((A + i, B + j, B + i, +1))
    last = ring_at[-1]
    for i in range(n):
        j = (i + 1) % n
        faces.append((base_center, last + i, last + j, -1))

    # One normal per face, and orient it against the hint so a winding slip cannot
    # produce an inside-out hull (which would break the silhouette union).
    out_faces = []
    norms = []
    for (i, j, k, hint) in faces:
        nrm = face_normal(pos[i], pos[j], pos[k])
        mid = ((pos[i][0] + pos[j][0] + pos[k][0]) / 3.0,
               (pos[i][1] + pos[j][1] + pos[k][1]) / 3.0, 0.0)
        if hint > 0:
            if nrm[0] * mid[0] + nrm[1] * mid[1] < 0.0:
                i, j = j, i
        else:
            if nrm[2] > 0.0:
                i, j = j, i
        out_faces.append((i, j, k))
        norms.append(face_normal(pos[i], pos[j], pos[k]))

    uv = [(0.5, 0.5) for _ in pos]
    out = ["# generated by gen_fuselage.py (r=%.6g h=%.6g, flat)" % (r, h),
           "o Fuselage"]
    for p in pos:
        out.append("v %.6f %.6f %.6f" % p)
    for t in uv:
        out.append("vt %.6f %.6f" % t)
    for v in norms:
        out.append("vn %.6f %.6f %.6f" % v)
    for fidx, (i, j, k) in enumerate(out_faces):
        fvn = fidx + 1
        out.append("f %d/%d/%d %d/%d/%d %d/%d/%d" % (
            i + 1, i + 1, fvn,
            j + 1, j + 1, fvn,
            k + 1, k + 1, fvn))
    out.append("")

    with open(a.dst, "w") as f:
        f.write("\n".join(out))
    print("%s: %d verts, %d faces (r=%.6g h=%.6g)" % (a.dst, len(pos), len(out_faces), r, h))


if __name__ == "__main__":
    main()
