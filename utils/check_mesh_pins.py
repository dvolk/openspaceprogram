def self_test():
    """Why each rule above still fires, or the reasons it stopped firing."""
    bad = []
    tmpd = tempfile.mkdtemp(prefix="meshpins_selftest_")
    for k, (want_faces, label, text, phrase) in enumerate(SELFTEST):
        path = os.path.join(tmpd, "case%d.obj" % k)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        problems = topo_problems(path, want_faces)
        if phrase == "" and problems:
            bad.append("self-test `%s` should be clean, got: %s" % (label, problems))
        elif phrase and not any(phrase in p for p in problems):
            bad.append("self-test `%s` should report a problem naming %r, got: %s"
                       % (label, phrase, problems))
    return bad


def regenerate(script, argv, outs, out_root):
    """Run one generator so its outputs land under out_root/res/. Returns its argv."""
    cmd = [sys.executable, os.path.join(HERE, script)] + list(argv)
    if script in IN_PLACE:
        cmd += ["--out", out_root]
    else:
        assert len(outs) == 1, (
            "%s writes more than one file but takes a destination path: split the pin" % script)
        dst = os.path.join(out_root, "res", outs[0])
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        cmd.append(dst)
    return cmd


def main():
    verbose = "--verbose" in sys.argv
    # --committed runs the stdlib half only: TOPO against the shipped text, plus the
    # coverage scan. It regenerates nothing, so it needs no trimesh and runs on the lint
    # runner. It cannot say whether an asset still matches its generator -- that half
    # imports trimesh through the generators, so it belongs to `make test` (test-art).
    committed = "--committed" in sys.argv
    pinned = sum(len(outs) for _, _, outs in PINS)
    # A TOPO row naming something PINS never regenerates is a check that silently stops
    # running, which is the failure mode this whole file exists to avoid.
    assert set(TOPO) <= {o for _, _, outs in PINS for o in outs}, \
        "TOPO lists an asset that PINS does not regenerate"
    topo_ran = 0
    # A pin whose asset has gone missing is the loudest failure there is: the gate would
    # otherwise compare nothing and stay green.
    for _, _, outs in PINS:
        for rel in outs:
            if not os.path.exists(os.path.join(REPO, "res", rel)):
                print("FAIL: pinned asset is gone: res/%s" % rel)
                return 1
    # The other direction: an excuse naming a file that has been deleted leaves the coverage
    # check accounting for an asset that no longer exists, so the pile still looks closed.
    for rel in UNPINNED:
        if not os.path.exists(os.path.join(REPO, "res", rel)):
            print("FAIL: unpinned excuse names an asset that is gone: res/%s" % rel)
            return 1

    st_fail = self_test()
    drift = list(st_fail)
    if committed:
        # The no-dependency half: the shipped text against TOPO, no generators run.
        for rel in sorted(TOPO):
            topo_ran += 1
            for why in topo_problems(os.path.join(REPO, "res", rel), TOPO[rel]):
                drift.append("res/%s: %s" % (rel, why))
    else:
        tmp = tempfile.mkdtemp(prefix="meshpins_", dir=os.path.join(REPO, "tmp"))
        for script, argv, outs in PINS:
            root = os.path.join(tmp, script[:-3] + "_" + "_".join(argv))
            cmd = regenerate(script, argv, outs, root)
            r = subprocess.run(cmd, capture_output=True, text=True)
            if r.returncode != 0:
                drift.append("%s %s: exit %d: %s"
                             % (script, " ".join(argv), r.returncode,
                                (r.stderr.strip().splitlines() or ["(no stderr)"])[-1]))
                continue
            for rel in outs:
                made, ship = os.path.join(root, "res", rel), os.path.join(REPO, "res", rel)
                if not os.path.exists(made):
                    drift.append("%s: wrote no res/%s" % (script, rel))
                    continue
                if open(made, "rb").read() != open(ship, "rb").read():
                    drift.append("res/%s is not what %s %s writes today"
                                 % (rel, script, " ".join(argv)))
                    continue
                if rel in TOPO:
                    topo_ran += 1
                    for why in topo_problems(made, TOPO[rel]):
                        drift.append("res/%s: %s" % (rel, why))

    # Coverage: every generated-asset CLAIM needs a pin or a reason.
    unclaimed = []
    for name in sorted(os.listdir(os.path.join(REPO, "res", "meshes"))):
        if not name.endswith(".obj"):
            continue
        rel = "meshes/" + name
        first = open(os.path.join(REPO, "res", rel), encoding="utf-8",
                     errors="replace").readline()
        if not HEADER.match(first):
            continue
        if rel not in {o for _, _, outs in PINS for o in outs} and rel not in UNPINNED:
            unclaimed.append(rel)

    for line in drift:
        print("FAIL: %s" % line)
    for rel in unclaimed:
        print("FAIL: res/%s claims to be generated but is neither pinned nor excused in "
              "utils/check_mesh_pins.py" % rel)
    if verbose or not (drift or unclaimed):
        head = ("art topology: shipped files checked as committed, no generators run"
                if committed else
                "mesh pins: %d assets regenerated from %d generators, %d drifted"
                % (pinned, len({s for s, _, _ in PINS}), len(drift) - len(st_fail)))
        print("%s, %d paintable-topology checks, %d self-test rules, %d self-test "
              "failures, %d claims excused, %d claims unpinned"
              % (head, topo_ran, len(SELFTEST), len(st_fail), len(UNPINNED),
                 len(unclaimed)))
        if topo_ran < len(TOPO):
            print("note: %d of %d TOPO rows were skipped because their asset did not "
                  "regenerate byte-exact" % (len(TOPO) - topo_ran, len(TOPO)))
        if topo_ran < len(TOPO):
            print("note: %d of %d TOPO rows were skipped because their asset did not "
                  "regenerate byte-exact" % (len(TOPO) - topo_ran, len(TOPO)))
    return 1 if (drift or unclaimed) else 0


