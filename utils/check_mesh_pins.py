HEADER = re.compile(r"^# generated by (gen_\w+\.py) \(")

# Paintability, asserted on the regenerated text rather than eyeballed in a modeller.
# path -> face count the generator must emit. The engine is blind to all of it --
# Mesh::AssImpFromFile runs aiProcess_Triangulate, so quads and ngons collapse to
# triangles on import and a mesh whose UVs are all one point still renders fine under a
# flat fill -- so a generator can regress into art that ships green and cannot be
# painted. Whoever opens the part in Blender notices: a triangulated wall unwraps into
# zig-zag slivers, overlapping islands mean painting one panel changes several, and a cap
# corner that carries the wall's normal shades a flat end as a shallow dome.
# utils/inspect_mesh_blender.py prints the same properties for looking at; this is the
# gate, stdlib on purpose -- Blender is not a build or CI dependency.
TOPO = {
    "meshes/adapter_r1.5to1.obj": 34,
    "meshes/adapter_r1.5to2.25.obj": 34,
    "meshes/adapter_r1to1.5.obj": 34,
    "meshes/adapter_r1to2.25.obj": 34,
    "meshes/adapter_r2.25to1.5.obj": 34,
    "meshes/adapter_r2.25to1.obj": 34,
    "meshes/capsule_cyl_r1h2.obj": 34,     # 32 wall quads + one ngon per end
}
TOPO_MIN_UV_AREA = 0.5


def topo_problems(path, want_faces):
    """Why this .obj would be hard to paint, or [] if it is paintable."""
    uvs, faces = [], []      # faces: (vertex idx, uv idx, normal idx) per corner
    with open(path, encoding="utf-8", errors="replace") as fh:
        for ln in fh:
            if ln.startswith("vt "):
                t = ln.split()
                uvs.append((float(t[1]), float(t[2])))
            elif ln.startswith("f "):
                c = [p.split("/") for p in ln.split()[1:]]
                faces.append(([int(x[0]) for x in c],
                              [int(x[1]) for x in c] if len(c[0]) > 1 else [],
                              [int(x[2]) for x in c] if len(c[0]) > 2 else []))
    bad = []
    tri = sum(1 for f in faces if len(f[0]) == 3)
    if tri:
        bad.append("%d triangles: the authored family is wall quads plus one ngon per "
                   "end, and a triangulated wall unwraps into zig-zag slivers" % tri)
    if len(faces) != want_faces:
        bad.append("%d faces, expected %d" % (len(faces), want_faces))
    mixed = sum(1 for f in faces if len(set(f[2])) != 1)
    if mixed:
        bad.append("%d faces carry more than one normal, so a face's own flat shading "
                   "blends into whatever meets it" % mixed)
    if any(not f[1] for f in faces):
        bad.append("a face has no uv, so it has no canvas to paint on")
        return bad

    # UV islands: faces joined across an edge only when that edge carries the same UV
    # on both sides. A seam -- the same vertex at two different UVs -- breaks the join,
    # which is exactly what one-island-per-face means.
    parent = list(range(len(faces)))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    by_edge = {}
    for k, f in enumerate(faces):
        vi = f[0]
        for j in range(len(vi)):
            a, b = vi[j], vi[j - 1]
            by_edge.setdefault((a, b) if a < b else (b, a), []).append((k, j))
    for sides in by_edge.values():
        if len(sides) != 2:
            continue
        (ka, ja), (kb, jb) = sides
        ua, ub = faces[ka][1], faces[kb][1]
        if ua[ja] == ub[jb] and ua[ja - 1] == ub[jb - 1]:
            ra, rb = find(ka), find(kb)
            if ra != rb:
                parent[rb] = ra
    islands = len({find(k) for k in range(len(faces))})
    if islands != len(faces):
        bad.append("%d uv islands for %d faces: paint one patch and several change"
                   % (islands, len(faces)))

    area = 0.0
    for f in faces:
        pts = [uvs[i - 1] for i in f[1]]
        a = 0.0
        for i in range(len(pts)):
            x1, y1 = pts[i]
            x2, y2 = pts[(i + 1) % len(pts)]
            a += x1 * y2 - x2 * y1
        area += abs(a) * 0.5
    if area < TOPO_MIN_UV_AREA:
        bad.append("uv islands cover %.3f of the canvas (min %.2f): the texture is being "
                   "read as almost one colour whatever it holds" % (area, TOPO_MIN_UV_AREA))
    return bad



def regenerate(script, argv, outs, out_root):
    """Run one generator so its outputs land under out_root/res/. Returns its argv."""
    cmd = [sys.executable, os.path.join(HERE, script)] + list(argv)
    if script in IN_PLACE:
        cmd += ["--out", out_root]
    else:
        assert len(outs) == 1, (
            "%s writes more than one file but takes a destination path: split the pin" % script)
        dst = os.path.join(out_root, "res", outs[0])
        os.makedirs(os.path.dirname(dst), exist_ok=True)
        cmd.append(dst)
    return cmd


def main():
    verbose = "--verbose" in sys.argv
    pinned = sum(len(outs) for _, _, outs in PINS)
    # A pin whose asset has gone missing is the loudest failure there is: the gate would
    # otherwise compare nothing and stay green.
    for _, _, outs in PINS:
        for rel in outs:
            if not os.path.exists(os.path.join(REPO, "res", rel)):
                print("FAIL: pinned asset is gone: res/%s" % rel)
                return 1

    drift = []
    tmp = tempfile.mkdtemp(prefix="meshpins_", dir=os.path.join(REPO, "tmp"))
    for script, argv, outs in PINS:
        root = os.path.join(tmp, script[:-3] + "_" + "_".join(argv))
        cmd = regenerate(script, argv, outs, root)
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            drift.append("%s %s: exit %d: %s"
                         % (script, " ".join(argv), r.returncode,
                            (r.stderr.strip().splitlines() or ["(no stderr)"])[-1]))
            continue
        for rel in outs:
            made, ship = os.path.join(root, "res", rel), os.path.join(REPO, "res", rel)
            if not os.path.exists(made):
                drift.append("%s: wrote no res/%s" % (script, rel))
                continue
            if open(made, "rb").read() != open(ship, "rb").read():
                drift.append("res/%s is not what %s %s writes today"
                             % (rel, script, " ".join(argv)))
                continue
            if rel in TOPO:
                for why in topo_problems(made, TOPO[rel]):
                    drift.append("res/%s: %s" % (rel, why))

    # Coverage: every generated-asset CLAIM needs a pin or a reason.
    unclaimed = []
    for name in sorted(os.listdir(os.path.join(REPO, "res", "meshes"))):
        if not name.endswith(".obj"):
            continue
        rel = "meshes/" + name
        first = open(os.path.join(REPO, "res", rel), encoding="utf-8",
                     errors="replace").readline()
        if not HEADER.match(first):
            continue
        if rel not in {o for _, _, outs in PINS for o in outs} and rel not in UNPINNED:
            unclaimed.append(rel)

    for line in drift:
        print("FAIL: %s" % line)
    for rel in unclaimed:
        print("FAIL: res/%s claims to be generated but is neither pinned nor excused in "
              "utils/check_mesh_pins.py" % rel)
    if verbose or not (drift or unclaimed):
        print("mesh pins: %d assets regenerated from %d generators, %d drifted, "
              "%d paintable-topology checks, %d claims excused, %d claims unpinned"
              % (pinned, len({s for s, _, _ in PINS}), len(drift), len(TOPO),
                 len(UNPINNED), len(unclaimed)))
    return 1 if (drift or unclaimed) else 0


if __name__ == "__main__":
    sys.exit(main())
