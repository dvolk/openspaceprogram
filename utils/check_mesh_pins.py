"""The drift pin for generated art (#1051).

res/systems/*.json and res/data/parts.json have had a regenerate-and-weigh gate for years
(#186: a Kuiper radius sat 1.5x out for two days because nothing regenerated it). The meshes
and textures the same kind of script writes had nothing: a generator could change and the
shipped asset would silently stop matching it, and -- the sharper edge -- four of the
generators wrote into res/ with no way to point them elsewhere, so an exploratory run
rewrote a shipped asset in passing (gen_gear.py has no argparse at all: `python3
utils/gen_gear.py --help` just generated the gear).

So: regenerate into a temp tree, byte-compare against the committed file, and fail on drift.
Byte-exact, not "close enough" -- 29 of the 33 assets that declare their own provenance
reproduce exactly today, so an exact comparison costs nothing and catches a formatter
version bump, an axis typo, a float that stopped rounding the same way.

Every generator named in PINS below was run to build the table, and the argv is the one its
own output header records (`# generated by gen_adapter.py (frustum r1=1.5 r2=1 h=0.75)`).
Coverage is checked rather than assumed: any res/meshes/*.obj that CLAIMS to be generated has
to appear in PINS or in UNPINNED with a reason, so adding a generated asset without a pin
fails here rather than joining the unpinned pile. Textures carry no header, so they are only
as covered as this list says (gen_flat_tex's fills and gen_terrain_detail's albedo map are
not pinned -- see UNPINNED).

Byte-exactness catches a generator that drifted. It does not catch one that got WORSE in a
way the engine cannot see, so TOPO below also checks the regenerated text for the topology
the hand-authored art uses -- wall quads and one ngon per end, one normal per face -- and
for UVs a painter can work on. The island rule is deliberately stricter than the
Blender-authored family, which lathes its wall as one continuous strip (3 islands across 34
faces): a generator has no reason to join cells, so per-face cells are what it has to keep.
See the comment on TOPO for what each check is for, and utils/inspect_mesh_blender.py for
reading the same properties in the editor.

Every rule in topo_problems() has a case in SELFTEST that must make it fire, run on every
invocation before any asset is weighed. That exists because the first version's island
compare could not fail and the seven green pins were quoted as proof (#1170 review round);
the summary line reports the rules run and the failures, so a rule that goes silent stops
the gate.

Usage: python3 utils/check_mesh_pins.py [--verbose] [--committed]
"""
