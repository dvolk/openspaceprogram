#!/usr/bin/env python3
"""Generate THIRD-PARTY.md and the deb's licence-text install list (#1002).

`make deb` conveys ONE binary that statically links SDL3, SDL_image (with the libpng and
zlib it builds), SDL_mixer (with stb_vorbis), GLEW, assimp, bullet3, and header-only glm,
imgui, implot, CLI11 and nlohmann/json. Nothing in the repo recorded any of it: no
third-party section, a debian/copyright that claims our own two licences for every file,
and no way to answer "which version of X are we shipping?" for the cases that are not
submodules (GLEW arrives from a tarball URL, the two JSON/CLI headers are bare files).

Permissive is not the same as free-of-conditions: zlib, MIT, BSD and Apache-2.0 each ask
for the copyright notice and the licence text to travel with the binary. So this writes
the notice down, and `make deb` puts the texts in /usr/share/doc/openspaceprogram/.

The pins come from what the repo already keeps machine-readable -- .gitmodules plus the
gitlinks it records, bootstrap.sh's GLEW_VER/GLEW_SHA, and the version macros inside the
two vendored headers -- and the licence is read from each library's own file, never
guessed. A file that matches no known shape is recorded as `unknown` with the path to
read, because an invented SPDX tag is worse than an admitted unknown (this tracker has
already been burned once by inferred data that read like decided data).

Outputs:
  THIRD-PARTY.md               the record, committed
  THIRD-PARTY/<lib>-<file>     each library's own notice text, copied out of wherever it
                               lives under a name that says whose it is
  utils/third-party.install    debian/install lines copying each licence text into the
                               package. It deliberately does NOT live in utils/debian/:
                               dpkg reads debian/<name>.install as the file list of a
                               binary package called <name>, so a fragment parked there
                               would ask dpkg-buildpackage to build a "third-party"
                               package. make_deb.sh appends it to debian/install instead.

Usage: python3 utils/gen_third_party.py [--check]   (--check exits 1 on drift)
"""
import argparse
import hashlib
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)

GEN_NOTE = ("Generated by utils/gen_third_party.py -- edit the script, not this file "
            "(--check fails when the file and the repo's pins disagree).")


def sh(argv):
    """Run in the repo and return stdout, or None if git is unavailable or the command
    failed. Nothing here may hard-fail on a tree without git metadata."""
    try:
        out = subprocess.run(argv, cwd=REPO, capture_output=True, text=True)
    except OSError:
        return None
    if out.returncode != 0:
        return None
    return out.stdout


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def first_text(path):
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def flatten(text):
    """Licence texts wrap at ~72 columns, so a phrase lands across a line break as often
    as not (libpng's does). Match on collapsed whitespace, never on the raw file."""
    return re.sub(r"\s+", " ", text)


# Known licence shapes, keyed on phrases the texts themselves carry. Ordered with the more
# specific first: BSD-3's preamble is BSD-2's.
LIC_PATTERNS = [
    # Named by the text itself ("PNG Reference Library License version 2"), which is why
    # it goes first: its permission clause reads close to MIT but is not MIT.
    ("Libpng-2.0", re.compile(r"PNG Reference Library License version 2", re.I)),
    ("Apache-2.0", re.compile(r"Apache License\s+Version 2\.0", re.I)),
    ("MIT", re.compile(r"Permission is hereby granted,? free of charge", re.I)),
    ("ISC", re.compile(r"Permission to use, copy, modify,?(?: and/or distribute)? "
                       r"this software for any purpose", re.I)),
    ("BSD", re.compile(r"Redistribution and use in source and binary forms", re.I)),
    ("Zlib", re.compile(r"This software is provided 'as-is'", re.I)),
]

LICENCE_FILE_NAMES = ("LICENSE", "LICENSE.txt", "LICENSE.md", "COPYING", "COPYING.txt",
                      "copying.txt", "copyright", "License.txt")


def spdx_of(text):
    """The library's own SPDX tag, if it states one. Only used where there is no separate
    licence file: a header carrying `SPDX-License-Identifier: MIT` is upstream speaking,
    which is not the same as a guess."""
    m = re.search(r"SPDX-License-Identifier:\s*([A-Za-z0-9.+-]+)", text)
    return m.group(1) if m else None


def licence_of(paths):
    """(name, file it was read from) for the first candidate that matches a known shape.

    `unknown` with the path is a deliberate answer: it says the text is there and nobody
    has read it into a tag. `none found` says the library ships no notice file at all,
    which for a vendored single header means the notice is inside the source."""
    found = []
    for p in paths:
        if not os.path.isfile(p):
            continue
        text = first_text(p)
        if not text.strip():
            continue
        found.append(p)
        flat = flatten(text)
        name = None
        for tag, rx in LIC_PATTERNS:
            if rx.search(flat):
                name = tag
                break
        if name == "BSD":
            # The third clause is "neither the name ... nor the names of its
            # contributors"; without it the same preamble is the two-clause text.
            name = ("BSD-3-Clause" if re.search(r"neither the name", flat, re.I)
                    else "BSD-2-Clause")
        if not name:
            name = spdx_of(text)
        if name:
            return name, os.path.relpath(p, REPO)
    if found:
        return "unknown", os.path.relpath(found[0], REPO)
    return "none found", None


def license_files(dirpath, extra=()):
    """Candidate notice files in one directory, in the order a reader would look, then
    anything named explicitly (a vendored header, whose notice is in its own body)."""
    out = [os.path.join(dirpath, n) for n in LICENCE_FILE_NAMES]
    out += list(extra)
    return out


def submodule_entries():
    """(path, url) per gitlink, read line by line -- a block regex has to stop at the
    next section, and these files have no closing marker to stop at."""
    txt = first_text(os.path.join(REPO, ".gitmodules"))
    entries, cur = [], None
    for line in txt.splitlines():
        s = line.strip()
        if s.startswith("[submodule"):
            cur = {"path": "", "url": ""}
            entries.append(cur)
        elif cur is not None and "=" in s:
            key, val = s.split("=", 1)
            key, val = key.strip().lower(), val.strip()
            if key == "path":
                cur["path"] = val
            elif key == "url":
                cur["url"] = val
    return [e for e in entries if e["path"]]


def submodule_status():
    """path -> (sha, describe, moved) from `git submodule status`. The leading flag
    matters: '+' means the checkout is not on the gitlink the superproject records, which
    is exactly the thing a licence/version record must not hide."""
    out = {}
    for line in (sh(["git", "submodule", "status"]) or "").splitlines():
        if not line.strip():
            continue
        flag, body = "", line
        if body[0] in (" ", "+", "-", "U"):
            flag, body = body[0], body[1:]
        parts = body.split(None, 2)
        if len(parts) < 2:
            continue
        sha, path = parts[0], parts[1]
        rest = parts[2] if len(parts) > 2 else ""
        out[path] = (sha, rest.strip("()"), flag == "+")
    return out


def bootstrap_glew():
    """GLEW's pin: bootstrap.sh fetches the release tarball, so the version and the
    checksum live there rather than in a gitlink."""
    txt = first_text(os.path.join(REPO, "bootstrap.sh"))
    ver = re.search(r"^GLEW_VER=(\S+)", txt, re.M)
    sha = re.search(r"^GLEW_SHA=([0-9a-f]{64})", txt, re.M)
    return (ver.group(1) if ver else "unknown",
            sha.group(1) if sha else "unknown")


def header_version(path, patterns):
    """A version assembled from the macros a header defines (joined with '.')."""
    txt = first_text(path)
    parts = []
    for rx in patterns:
        m = re.search(rx, txt)
        if not m:
            return "unknown"
        parts.append(m.group(1))
    return ".".join(parts)


def source_notice(path, cap=80):
    """The leading `//` comment block of a vendored source file, verbatim.

    CLI11 and nlohmann/json arrive as one header with no separate notice file: their
    copyright and permission terms ARE that block. MIT and BSD ask that the notice be
    reproduced in the material that travels with a binary, so the record quotes it rather
    than pointing at a 1 MB header nobody opens."""
    out = []
    for ln in first_text(path).splitlines():
        s = ln.strip()
        if s.startswith("//") or not s:
            out.append(ln.rstrip())
            if len(out) >= cap:
                break
            continue
        break
    body = "\n".join(out).strip()
    return body if re.search(r"copyright|public domain", body, re.I) else ""


def tail_notice(path, cap=160):
    """The last block comment of a file. stb_vorbis says "See end of file for license
    information" at the top, so its licence lives at the bottom -- quoting the top block
    would reproduce a pointer instead of a notice. The cap is generous on purpose: a
    licence cut off mid-sentence is worse than one quoted whole."""
    blocks = re.findall(r"/\*.*?\*/", first_text(path), re.S)
    for b in reversed(blocks):
        if re.search(r"public domain|licen", b, re.I):
            return "\n".join(b.splitlines()[:cap]).strip()
    return ""


TEXT_DIR = "THIRD-PARTY"


def slug(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")


def render_texts(rows):
    """[(path, content)] for the notice files the package ships.

    Named by library, not by their own basename, because ten of these are called
    LICENSE.txt: dh_install copies into one directory by basename, and an early version of
    this shipped three files for eleven libraries -- each copy overwriting the last
    (measured against a built .deb). Committing the copy is also what makes a notice
    checkable for drift, rather than a path into someone else's checkout that only exists
    after bootstrap.sh has run.
    """
    out = []
    for r in rows:
        f = r["license_file"]
        # A vendored header or decoder carries its notice in its own body; THIRD-PARTY.md
        # quotes that, and shipping a 1 MB header as a doc file is noise, not attribution.
        if not f or f.endswith((".c", ".h", ".hpp")):
            continue
        base = os.path.basename(f)
        out.append((os.path.join(TEXT_DIR, "%s-%s" % (slug(r["name"]), base)),
                    first_text(os.path.join(REPO, f))))
    return out


def collect():
    """Every static input of the release link, as rows for the record."""
    rows = []
    status = submodule_status()
    for e in submodule_entries():
        lic, licfile = licence_of(license_files(os.path.join(REPO, e["path"])))
        sha, desc, moved = status.get(e["path"], ("not initialised", "", False))
        rows.append({"name": os.path.basename(e["path"]), "kind": "submodule",
                     "where": e["path"], "url": e["url"],
                     "pin": sha[:12] if len(sha) > 12 else sha,
                     "describe": desc, "moved": moved,
                     "license": lic, "license_file": licfile})

    ver, sha = bootstrap_glew()
    lic, licfile = licence_of(license_files(os.path.join(REPO, "middleware/glew")))
    rows.append({"name": "GLEW", "kind": "release tarball", "where": "middleware/glew",
                 "url": "https://sourceforge.net/projects/glew/files/glew/",
                 "pin": "%s (tarball sha256 %s)" % (ver, sha[:16]), "describe": "",
                 "moved": False, "license": lic, "license_file": licfile})

    for name, path, up, vrx in (
        ("CLI11", "middleware/CLI11/CLI11.hpp",
         "https://github.com/CLIUtils/CLI11",
         [r'#define\s+CLI11_VERSION\s+"([^"]+)"']),
        ("nlohmann/json", "middleware/nlohmann/json.hpp",
         "https://github.com/nlohmann/json",
         [r'#define\s+NLOHMANN_JSON_VERSION_MAJOR\s+(\d+)',
          r'#define\s+NLOHMANN_JSON_VERSION_MINOR\s+(\d+)',
          r'#define\s+NLOHMANN_JSON_VERSION_PATCH\s+(\d+)']),
    ):
        full = os.path.join(REPO, path)
        # No notice file beside these two: the copyright and licence sit in the header's
        # own comment, so the file is its own notice.
        lic, licfile = licence_of(license_files(os.path.dirname(full), extra=[full]))
        rows.append({"name": name, "kind": "vendored header", "where": path, "url": up,
                     "pin": "%s (file sha256 %s)"
                     % (header_version(full, vrx), sha256(full)[:16]),
                     "describe": "", "moved": False,
                     "license": lic, "license_file": licfile,
                     "quote": source_notice(full)})

    # libpng and zlib are not ours to pin: SDL_image builds them from sources it carries,
    # so their version comes from their own headers and their provenance is the SDL_image
    # checkout.
    extra_urls = {"libpng": "https://www.libpng.org/pub/png/libpng.html",
                  "zlib": "https://zlib.net"}
    for name, hdr, vrx in (
        ("libpng", "libpng/png.h", [r'#define\s+PNG_LIBPNG_VER_STRING\s+"([^"]+)"']),
        ("zlib", "zlib/zlib.h", [r'#define\s+ZLIB_VERSION\s+"([^"]+)']),
    ):
        base = os.path.join(REPO, "middleware/sdl3-image/external")
        full = os.path.join(base, hdr)
        lic, licfile = licence_of(license_files(os.path.dirname(full)))
        rows.append({"name": name, "kind": "built by SDL_image",
                     "where": "middleware/sdl3-image/external/%s"
                     % os.path.dirname(hdr),
                     "url": extra_urls[name], "pin": header_version(full, vrx),
                     "describe": "", "moved": False,
                     "license": lic, "license_file": licfile})

    # stb_vorbis rides inside SDL_mixer's own source tree (a decoder), not a submodule.
    stb = os.path.join(REPO, "middleware/sdl-mixer/src/stb_vorbis/stb_vorbis.h")
    if os.path.isfile(stb):
        lic, licfile = licence_of(license_files(os.path.dirname(stb), extra=[stb]))
        if "available under 2 licenses" in first_text(stb):
            # The file names its own alternatives, so naming them is reading rather than
            # picking a side: a bare "MIT" would hide that the public-domain grant exists.
            lic = "MIT or Unlicense (the file's own two alternatives)"
        rows.append({"name": "stb_vorbis", "kind": "vendored in SDL_mixer",
                     "where": os.path.relpath(stb, REPO),
                     "url": "https://github.com/nothings/stb",
                     "pin": "file sha256 %s" % sha256(stb)[:16], "describe": "",
                     "moved": False, "license": lic, "license_file": licfile,
                     "quote": tail_notice(stb)})
    return rows


def render(rows):
    out = ["# Third-party code",
           "",
           GEN_NOTE,
           "",
           "The release binary is linked static: `libSDL3.a`, `libSDL3_image.a`, "
           "`libSDL3_mixer.a`, `libGLEW.a`, `libassimp.a`, `libBulletDynamics.a`, "
           "`libBulletCollision.a`, `libLinearMath.a`, `libpng16.a`, `libz.a`, plus the "
           "header-only libraries compiled straight in. System libraries (`-lGL`, the X11 "
           "set) are dynamic and are not ours to ship.",
           "",
           "Each row is what the repo actually pins, read from where that pin lives: the "
           "gitlink for a submodule, `bootstrap.sh` for the GLEW tarball, the version "
           "macro plus a file checksum for a vendored header. The licence name comes from "
           "the library's own text; `unknown` means a notice file exists and its shape is "
           "unrecognised -- read the path rather than guessing at a tag. `none found` "
           "means the library ships no notice file at all.",
           "",
           "| library | how it arrives | upstream | pinned at | licence | notice text |",
           "| --- | --- | --- | --- | --- | --- |"]
    for r in rows:
        pin = r["pin"]
        if r["describe"] and r["describe"] != r["pin"]:
            pin = "%s `%s`" % (r["describe"], pin)
        if r["moved"]:
            pin += " -- checkout moved off the recorded gitlink"
        text = ("inside the source, quoted below" if r.get("quote")
                else "`%s`" % r["license_file"] if r["license_file"] else "-")
        out.append("| %s | %s | %s | %s | %s | %s |"
                   % (r["name"], r["kind"], r["url"], pin, r["license"], text))
    quoted = [r for r in rows if r.get("quote")]
    if quoted:
        out += ["",
                "## Notices that live inside a source file",
                "",
                "These arrive as one source file with no separate licence text, so the",
                "notice is quoted here verbatim from the file the binary is built from --",
                "MIT and BSD ask that it travel with the distribution in documentation,",
                "and a 1 MB header nobody opens does not carry it.",
                ""]
        for r in quoted:
            out += ["### %s (`%s`)" % (r["name"], r["where"]), "", "```",
                    r["quote"], "```", ""]
    out += ["",
            "## Conveying this",
            "",
            "zlib, MIT, BSD and Apache-2.0 each require the copyright notice and the "
            "licence text to travel with a binary. This script copies every notice "
            "named above into `%s/`, renamed for its library -- `glm-copying.txt`, not "
            "`copying.txt`, because eleven of these share two basenames and would "
            "overwrite each other in one directory. The release artifacts carry that "
            "directory: `make deb` installs it into "
            "`/usr/share/doc/openspaceprogram/third-party/` from "
            "`utils/third-party.install`, which this script also writes; the tarballs "
            "carry it as `third-party/` next to the binary, the AppImage as "
            "`usr/share/doc/third-party/`. This file "
            "rides next to `LICENSE.md`." % TEXT_DIR,
            "",
            "Our own code is AGPL-3.0 and `res/` is CC-BY-SA-3.0, in `LICENSE.md`. That "
            "claim covers our work only: everything under `middleware/` keeps whatever "
            "its own library says it keeps.",
            ""]
    return "\n".join(out)


def render_install(texts):
    """debian/install lines for the notice copies this script writes. The sources are
    already named per library, so nothing in the package can collide."""
    out = ["# generated by utils/gen_third_party.py -- where each licence text lands in",
           "# the .deb (#1002). NOT inside utils/debian/: dpkg would read it as the file",
           "# list of a package named third-party. make_deb.sh appends it to",
           "# debian/install.",
           "#",
           "# Each source is a copy gen_third_party.py keeps in %s/ named for its library,"
           % TEXT_DIR,
           "# not the upstream basename: eleven libraries share two basenames",
           "# (LICENSE, LICENSE.txt), and dh_install copies by basename into one",
           "# directory, so the upstream names collapse to three files.",
           "THIRD-PARTY.md                            usr/share/doc/openspaceprogram/"]
    for p in texts:
        out.append("%-48s usr/share/doc/openspaceprogram/third-party/" % p[0])
    out.append("")
    return "\n".join(out)


def write_if_changed(path, text, check, label):
    old = first_text(path) if os.path.isfile(path) else None
    if old == text:
        return False
    if check:
        print("STALE: %s is not what the repo pins -- run: python3 "
              "utils/gen_third_party.py" % label)
        return True
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(text)
    print("wrote %s" % label)
    return False


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="fail (exit 1) if the committed files are not what the repo "
                         "pins; write nothing")
    args = ap.parse_args()
    rows = collect()
    texts = render_texts(rows)
    stale = write_if_changed(os.path.join(REPO, "THIRD-PARTY.md"), render(rows),
                             args.check, "THIRD-PARTY.md")
    for rel, body in texts:
        stale |= write_if_changed(os.path.join(REPO, rel), body, args.check, rel)
    stale |= write_if_changed(os.path.join(REPO, "utils/third-party.install"),
                              render_install(texts), args.check,
                              "utils/third-party.install")
    if args.check:
        if stale:
            return 1
        print("third-party record matches the repo's pins")
    else:
        print("%d third-party entries" % len(rows))
    return 0


if __name__ == "__main__":
    sys.exit(main())
