#!/usr/bin/env python3
"""Generate the runway .obj: a flat box slab. Long axis X, width Y, depth -Z.
The TOP face sits at z=0 (the building origin, like space_port.obj), so the
slab hangs below the deck a ship stands on. Shared verts + outward winding keep
it watertight for the collision hull and the volume check (utils/check_mesh.py).
"""

import argparse
import math


def cross(a, b):
    return (a[1]*b[2] - a[2]*b[1],
            a[2]*b[0] - a[0]*b[2],
            a[0]*b[1] - a[1]*b[0])


def sub(a, b):
    return (a[0]-b[0], a[1]-b[1], a[2]-b[2])


def norm(v):
    L = math.sqrt(v[0]*v[0] + v[1]*v[1] + v[2]*v[2])
    return (v[0]/L, v[1]/L, v[2]/L) if L else (0.0, 0.0, 0.0)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("dst", help="destination .obj")
    ap.add_argument("--length", type=float, default=900.0, help="X (default 900)")
    ap.add_argument("--width", type=float, default=30.0, help="Y (default 30)")
    ap.add_argument("--depth", type=float, default=4.0, help="-Z slab (default 4)")
    a = ap.parse_args()
    if a.length <= 0 or a.width <= 0 or a.depth <= 0:
        ap.error("length/width/depth must be > 0")

    hx, hy, d = a.length / 2.0, a.width / 2.0, a.depth
    corners = [( hx,  hy, 0.0), ( hx, -hy, 0.0), (-hx, -hy, 0.0), (-hx,  hy, 0.0),
               ( hx,  hy, -d), ( hx, -hy, -d), (-hx, -hy, -d), (-hx,  hy, -d)]
    face_idx = [
        (0, 1, 2), (0, 2, 3),    # top (+Z, the deck)
        (4, 5, 6), (4, 6, 7),    # bottom (-Z)
        (0, 4, 5), (0, 5, 1),    # +X end
        (2, 6, 7), (2, 7, 3),    # -X end
        (0, 3, 7), (0, 7, 4),    # +Y side
        (1, 5, 6), (1, 6, 2),    # -Y side
    ]

    # Outward winding: flip any face whose normal points toward the box centre.
    centre = (0.0, 0.0, -d / 2.0)
    acc = [[0.0, 0.0, 0.0] for _ in corners]
    faces = []
    for (i0, i1, i2) in face_idx:
        p0, p1, p2 = corners[i0], corners[i1], corners[i2]
        n = norm(cross(sub(p1, p0), sub(p2, p0)))
        c = ((p0[0]+p1[0]+p2[0])/3.0 - centre[0],
             (p0[1]+p1[1]+p2[1])/3.0 - centre[1],
             (p0[2]+p1[2]+p2[2])/3.0 - centre[2])
        if n[0]*c[0] + n[1]*c[1] + n[2]*c[2] < 0.0:
            i1, i2 = i2, i1
            n = (-n[0], -n[1], -n[2])
        faces.append((i0, i1, i2))
        for k in (i0, i1, i2):
            acc[k][0] += n[0]; acc[k][1] += n[1]; acc[k][2] += n[2]
    vn = [norm(t) for t in acc]

    out = ["# generated by gen_runway.py (length=%.6g width=%.6g depth=%.6g)"
           % (a.length, a.width, a.depth), "o Runway"]
    for v in corners:
        out.append("v %.6f %.6f %.6f" % v)
    for _ in corners:                      # flat-fill texture: UVs are a formality
        out.append("vt 0.000000 0.000000")
    for v in vn:
        out.append("vn %.6f %.6f %.6f" % v)
    for (i0, i1, i2) in faces:
        out.append("f %d/%d/%d %d/%d/%d %d/%d/%d" % (
            i0+1, i0+1, i0+1, i1+1, i1+1, i1+1, i2+1, i2+1, i2+1))
    out.append("")
    with open(a.dst, "w") as f:
        f.write("\n".join(out))
    print("%s: %d corners, %d faces" % (a.dst, len(corners), len(faces)))


if __name__ == "__main__":
    main()
