#!/usr/bin/env python3
"""Generate a part of revolution as a .obj: rings of profile, wall quads, cap ngons.

One generator for the lofted family -- the 6 tank adapters, the flat-nosed capsule,
the 3 nose caps, the 8 engine shrouds. They are the same shape read three ways: a
frustum between two stack radii, a straight wall, or an open tube.

    gen_lathe.py DST --r1 1.5 --r2 1 --height 0.75
    gen_lathe.py DST --profile "1@-0.25,0.6@0.15,0@0.5" --caps base --name NoseCap

Topology follows the art it sits beside (res/meshes/capsule.obj, tank_r1h3.obj): the
wall is one QUAD per segment per band, each closed end is ONE NGON, and every face
carries its own normal -- sharing a normal between a wall corner and the cap corner
that meets it at a right angle blends a flat end into a shallow dome (measured 90 deg
off the cap's own face normal, 138 deg on the steep adapters).

UVs are the part this file exists to fix. The adapter generator it replaced gave every face
the SAME grid cell, so a cap got 3 to 6 times the texel density of the wall it meets: half
the part painted sharp and half blurred (#1176). The nose cap and shroud generators left UVs
that collapse to one point, so painting them could not change the part at all (#1173). All
three of those scripts are gone; this one is pinned over all 18 meshes.

Here each face gets its OWN island, drawn congruent to itself -- a wall quad becomes an
isosceles trapezoid of its true edge lengths, a cap becomes a disc of its true radius --
and every island shares one scale, chosen as the largest that packs the canvas.
Congruent plus one scale is what makes texel density exactly equal across the part by
construction, rather than an operator's approximation of it: the gate measures the
ratio and finds 1.00 on all 18 of these meshes. It costs a fatter adapter most of its
canvas, because two discs are over half a fat adapter's surface, and the fix for that is
a bigger canvas (#1173), not a thinner part.

That rules out the continuous strip. A frustum's wall does not unroll into a
rectangle: isometrically it is an annulus sector (200 deg for r1.5to1, 268 deg for
r2.25to1, bounding box 4.4 to 8.0 m), and the rectangular "cylindrical unwrap" most
tools give instead maps both rims to the same width, so px/m differs by r1/r2 -- 2.25
on adapter_r2.25to1, over the gate's 2.0 ceiling. A strip is only exact on a straight
wall. Per-face islands are exact on every profile, and they keep the property the grid-cell
layout was after: a painter's patch belongs to one face, and the mip filter
(GL_LINEAR_MIPMAP_LINEAR, src/texture.cpp) cannot bleed it into its neighbour.
"""

import argparse
import math


def unit(v):
    L = math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2])
    return (v[0] / L, v[1] / L, v[2] / L) if L > 0 else (0.0, 0.0, 1.0)


def sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1],
            a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def parse_profile(ap, a):
    """The profile as [(radius, z), ...], low z first. --r1/--r2/--height is the
    two-ring shorthand every adapter already names."""
    if a.profile is not None:
        rings = []
        for tok in a.profile.split(","):
            tok = tok.strip()
            if not tok:
                continue
            try:
                r, z = tok.split("@")
                rings.append((float(r), float(z)))
            except ValueError:
                ap.error("bad profile token %r: want radius@z" % tok)
        if len(rings) < 2:
            ap.error("profile needs at least two rings")
        rings.sort(key=lambda t: t[1])
        return rings
    if a.height is None:
        a.height = max(a.r1, a.r2) / 2.0
    return [(a.r1, -a.height / 2.0), (a.r2, a.height / 2.0)]


def poly_area(poly):
    a = 0.0
    for i, (x0, y0) in enumerate(poly):
        x1, y1 = poly[(i + 1) % len(poly)]
        a += x0 * y1 - x1 * y0
    return abs(a) / 2.0


def pack(shapes, margin):
    """Largest scale at which the shapes fit a unit canvas, with that scale's positions.

    shapes is [(bbox_w, bbox_h, polygon_area), ...], one entry per face. Guillotine
    best-area fit, remainder split along whichever side has more left over, tried under
    several placement orders with the best result kept. What the order is worth depends on
    the part: on the fattest adapter the best and worst orders differ by a third of the
    canvas (uv scale 0.1864 against 0.1614, measured), and on a straight shroud not at all
    -- measured over the 18 pinned parts, 8 give the same scale for all five orders and
    none gives more than two distinct layouts, so the duplicates are dropped below rather
    than bisected. Fixed orders and a fixed tie-break keep it deterministic, which matters
    because the gate compares generated bytes, not a solver's luck. A shelf packer, by
    contrast, gave every cap disc a row of its own and left the rest of that row empty: on
    a fat adapter that lost a third of the canvas.

    One scale for every island, because equal density is the whole point of the layout. If
    the canvas cannot hold the floor, the gate says so and the part is wrong -- rather than
    the layout quietly thinning the flat ends, which is how #1176 started.
    Returns (scale, positions, turned).
    """
    areas = [shapes[k][2] for k in range(len(shapes))]
    keys = [lambda k: -max(shapes[k][:2]), lambda k: -shapes[k][1],
            lambda k: -shapes[k][0], lambda k: -areas[k], lambda k: areas[k]]
    # dict.fromkeys, not set: the order the orders are tried in has to be fixed, since the
    # best-of loop keeps the first layout that ties and the file's bytes ride on it.
    orders = list(dict.fromkeys(tuple(sorted(range(len(shapes)),
                                            key=lambda k: (keyf(k), k))) for keyf in keys))

    def fits(s, order):
        # Each island owns a gutter ring, so two neighbours keep 2*margin between their
        # polygons and the canvas edge keeps margin. A face may be laid on its side:
        # island orientation is free in uv space, and a wall quad rotated 90 deg fills a
        # short wide remainder that an upright one cannot.
        cell = [(shapes[k][0] * s + 2.0 * margin, shapes[k][1] * s + 2.0 * margin)
                for k in range(len(shapes))]
        free = [(0.0, 0.0, 1.0, 1.0)]
        pos, turned = {}, {}
        for k in order:
            w0, h0 = cell[k]
            pick = None
            for (w, h) in ((w0, h0),) if w0 == h0 else ((w0, h0), (h0, w0)):
                for i, (x, y, fw, fh) in enumerate(free):
                    if fw >= w and fh >= h:
                        key = (fw * fh - w * h, abs(fw - w) + abs(fh - h),
                               0 if (w, h) == (w0, h0) else 1, i)
                        if pick is None or key < pick[0]:
                            pick = (key, i, (w, h))
            if pick is None:
                return None
            x, y, fw, fh = free[pick[1]]
            w, h = pick[2]
            # add_face moved each polygon's bbox to (0, 0), so a cell of w x h holds it
            # with margin to spare on all four sides rather than two.
            pos[k] = (x + margin, y + margin)
            turned[k] = (w, h) != (w0, h0)
            free.pop(pick[1])
            if fw - w >= fh - h:
                free.append((x + w, y, fw - w, fh))
                free.append((x, y + h, w, fh - h))
            else:
                free.append((x, y + h, fw, fh - h))
                free.append((x + w, y, fw - w, h))
        return pos, turned

    # Search each order independently: the fits are monotone in s, so a bisection per
    # order finds its ceiling, and the best ceiling over orders is the layout.
    best_scale, best_pos, best_turned = 0.0, None, None
    for order in orders:
        lo, hi, got = 0.0, 4.0, None
        for _ in range(48):                  # ~1e-14 on a uv coordinate: bytes pin stably
            mid = (lo + hi) / 2.0
            p = fits(mid, order)
            if p is None:
                hi = mid
            else:
                lo, got = mid, p
        if lo > best_scale:
            best_scale, best_pos, best_turned = lo, got[0], got[1]
    return best_scale, best_pos, best_turned


def main():
    ap = argparse.ArgumentParser(description="lathe a radius profile into a solid of "
                                             "revolution for the lofted part family")
    ap.add_argument("dst", help="destination .obj")
    ap.add_argument("--profile", help='"radius@z" rings, sorted by z whatever the order '
                                     'given; overrides --r1/--r2/--height')
    ap.add_argument("--r1", type=float, default=1.0, help="radius at the -Z end")
    ap.add_argument("--r2", type=float, default=3.0, help="radius at the +Z end")
    ap.add_argument("--height", type=float, default=None,
                    help="height of a two-ring profile (default: max(r1, r2) / 2)")
    ap.add_argument("--caps", choices=["both", "base", "top", "none"], default="both",
                    help="which ends are closed (a shroud is open at both)")
    ap.add_argument("--segments", type=int, default=32)
    ap.add_argument("--margin", type=float, default=0.008,
                    help="gap between islands, as a fraction of the canvas")
    ap.add_argument("--name", default="Lathe", help="object name written into the file")
    a = ap.parse_args()
    rings = parse_profile(ap, a)
    n = a.segments
    if n < 3:
        ap.error("segments >= 3")
    if any(r < 0.0 or not math.isfinite(r) for r, _ in rings) or \
       any(not math.isfinite(z) for _, z in rings):
        ap.error("profile radii must be finite and >= 0, and z finite")
    if any(z2 <= z1 for (_, z1), (_, z2) in zip(rings, rings[1:])):
        ap.error("profile z must strictly increase")
    # A zero radius is the axis, so it belongs at an end of the profile (a cone, a nose
    # cap) -- never between two rings, whose band would have no wall to stand on.
    if all(r == 0.0 for r, _z in rings):
        ap.error("a profile of nothing but axis is not a solid")
    if any(r == 0.0 and i not in (0, len(rings) - 1) for i, (r, _z) in enumerate(rings)):
        ap.error("a zero radius has to be the first or last ring of the profile")
    # The gutter is what stops a mip level bleeding one island into the next, so a margin
    # under about one texel at the canvas these parts ask for (512^2) is a gutter in name.
    if not 0.001 <= a.margin <= 0.05:
        ap.error("--margin is a fraction of the canvas: 0.001 <= margin <= 0.05 "
                 "(0.001 is one texel at 512^2)")

    ang = [2.0 * math.pi * i / n for i in range(n)]
    # A zero-radius ring is the axis: one vertex, not n coincident ones. That is what
    # lets a cone (the nose cap) come from the same profile vocabulary as a frustum.
    verts = []
    ring_idx = []
    for r, z in rings:
        idx = []
        if r == 0.0:
            verts.append((0.0, 0.0, z))
            idx.append(len(verts) - 1)
        else:
            for th in ang:
                verts.append((r * math.cos(th), r * math.sin(th), z))
                idx.append(len(verts) - 1)
        ring_idx.append(idx)

    def chord(r):
        return 2.0 * r * math.sin(math.pi / n)

    # Faces: (ring indices, uv polygon congruent to the face at scale 1, bbox). Wall
    # quads run bottom, bottom+1, top+1, top. An end's ngon walks its ring BACKWARDS so
    # every edge it shares with the wall runs the opposite way in the two faces: that is
    # what keeps the shell closed and the winding consistent. A triangle fan would pass
    # that test too, but it hands the painter 32 slivers where there is one disc, and
    # the engine triangulates on import anyway.
    faces = []

    def add_face(idx, poly):
        # The packer gives an island a cell of its bbox size, so the polygon has to sit
        # with its bbox at (0, 0). A cap disc built about the origin instead parks half
        # of it outside the cell: off the canvas, or on top of a neighbour's island.
        xs = [p[0] for p in poly]
        ys = [p[1] for p in poly]
        x0, y0 = min(xs), min(ys)
        faces.append((idx, [(x - x0, y - y0) for (x, y) in poly],
                      max(xs) - x0, max(ys) - y0))

    for b in range(len(rings) - 1):
        r_lo, z_lo = rings[b]
        r_hi, z_hi = rings[b + 1]
        dz, dr = z_hi - z_lo, r_hi - r_lo
        if r_lo == 0.0 or r_hi == 0.0:
            # A cone band: one triangle per segment, congruent in UV -- base the chord
            # on the ring side, the legs the slant from the axis vertex.
            tip_up = r_hi == 0.0
            rim, tip = (ring_idx[b], ring_idx[b + 1][0]) if tip_up \
                else (ring_idx[b + 1], ring_idx[b][0])
            r = r_lo if tip_up else r_hi
            base = chord(r)
            leg = math.hypot(dz, r)
            htri = math.sqrt(max(leg * leg - (base / 2.0) ** 2, 0.0))
            tri = [(0.0, 0.0), (base, 0.0), (base / 2.0, htri)]
            for i in range(n):
                j = (i + 1) % n
                # The rim edge has to run the opposite way to the band it meets, so the
                # winding mirrors with which end of the axis the tip sits at: rim, rim+1,
                # tip going up the +Z cone, rim, tip, rim+1 going down the -Z one.
                idx = [rim[i], rim[j], tip] if tip_up else [rim[i], tip, rim[j]]
                add_face(idx, tri)
            continue
        c_lo, c_hi = chord(r_lo), chord(r_hi)
        slant = math.hypot(dz, dr)
        off = (c_lo - c_hi) / 2.0
        # The wall quad is planar -- an isosceles trapezoid with legs the slant -- but a
        # trapezoid whose chords differ stands shorter than its leg by the offset they
        # leave between the rim corners. Drawing it at the leg's full length would make
        # the legs sqrt(off^2 + slant^2) and overstate the island's area, which is the
        # density. |off| < |dr| <= slant, so the square root is always real.
        rise = math.sqrt(slant * slant - off * off)
        poly = [(0.0, 0.0), (c_lo, 0.0), (off + c_hi, rise), (off, rise)]
        for i in range(n):
            j = (i + 1) % n
            add_face([ring_idx[b][i], ring_idx[b][j],
                      ring_idx[b + 1][j], ring_idx[b + 1][i]], poly)
    for band, closed in ((0, a.caps in ("both", "base")),
                         (len(rings) - 1, a.caps in ("both", "top"))):
        if not closed or rings[band][0] == 0.0:
            continue      # an axis end is a point, not a face
        r, _z = rings[band]
        walk = list(reversed(range(n))) if band == 0 else list(range(n))
        idx = [ring_idx[band][k] for k in walk]
        order_ang = [ang[k] for k in walk]
        poly = [(r * math.cos(t), r * math.sin(t)) for t in order_ang]
        add_face(idx, poly)

    # Check the winding claim made above rather than trusting it: an edge shared by two
    # faces must run the opposite way in each, no edge may sit in more than two faces, and
    # the edges left single must be exactly the rims of the ends that are open. This is
    # the invariant the radial normal assert below cannot carry for a cap -- a cap's
    # centroid is on the axis and its normal is axial, so their dot product is exactly
    # zero whatever the winding is. Winding the base cap the same way as the wall was
    # measured to generate clean and to satisfy every gate rule (32 rim edges running the
    # same way in both faces, topo_problems() returning []).
    dirs = {}
    for idx, _poly, _w, _h in faces:
        for k in range(len(idx)):
            va, vb = idx[k], idx[k - 1]
            dirs.setdefault((va, vb) if va < vb else (vb, va), []).append((va, vb))
    singles = 0
    for key, dd in dirs.items():
        assert len(dd) <= 2, "edge %s belongs to %d faces" % (key, len(dd))
        if len(dd) == 1:
            singles += 1
        else:
            assert dd[0] != dd[1], "edge %s runs the same way in both its faces" % (key,)
    # Only the first and last rings can leave an edge unshared: a ring between two bands is
    # closed by both of them, and a ring on the axis closes itself into a point.
    open_rims = n * sum(
        1 for i, closed in ((0, a.caps in ("both", "base")),
                            (len(rings) - 1, a.caps in ("both", "top")))
        if rings[i][0] > 0.0 and not closed)
    assert singles == open_rims, \
           "%d single edges, expected %d rim edges for caps=%s" % (singles, open_rims, a.caps)

    shapes = [(f[2], f[3], poly_area(f[1])) for f in faces]
    scale, origin, turned = pack(shapes, a.margin)
    if not origin:
        ap.error("no uv layout fits: %d islands at margin %g exceed the canvas"
                 % (len(faces), a.margin))

    # One normal per face: flat shading, as the authored parts do it, and the reason a
    # flat end stays flat under the light. Every face here is planar -- a band of a
    # surface of revolution, or a ring perpendicular to the axis -- so its first three
    # corners carry the normal. Asserting it points away from the axis is what keeps the
    # winding conventions above honest: an inward face would shade as a hole.
    normals = []
    for idx, _poly, _w, _h in faces:
        nv = unit(cross(sub(verts[idx[1]], verts[idx[0]]), sub(verts[idx[2]], verts[idx[0]])))
        cx = sum(verts[i][0] for i in idx) / len(idx)
        cy = sum(verts[i][1] for i in idx) / len(idx)
        assert nv[0] * cx + nv[1] * cy >= 0.0, "a face normal points at the axis"
        normals.append(nv)

    uvs = []
    for k, (idx, poly, _w, _h) in enumerate(faces):
        ox, oy = origin[k]
        # A turned island enters the cell rotated a quarter turn: (u, v) -> (h - v, u).
        pts = [(_h - v, u) for (u, v) in poly] if turned[k] else poly
        for (u, v) in pts:
            uvs.append((ox + u * scale, oy + v * scale))

    # vt indices per face, as a running total instead of a rescan of the face list: the
    # f lines are the file's bulk and this runs once per corner.
    vbase, bases = 0, []
    for f in faces:
        bases.append(vbase)
        vbase += len(f[0])

    # Where the layout actually landed, against what the packer promised: each island
    # inside the canvas, and each pair keeping the gutter ring it was charged. The gate
    # checks both on the shipped file; checking them here means a packing bug fails the
    # build instead of shipping art that clips at the edge or paints through a neighbour.
    boxes = []
    for k in range(len(faces)):
        span = uvs[bases[k]:bases[k] + len(faces[k][0])]
        xs = [p[0] for p in span]
        ys = [p[1] for p in span]
        boxes.append((min(xs), min(ys), max(xs), max(ys)))
    for k, bx in enumerate(boxes):
        assert (bx[0] >= -1e-9 and bx[1] >= -1e-9
                and bx[2] <= 1.0 + 1e-9 and bx[3] <= 1.0 + 1e-9), \
               "island %d of %d falls outside the canvas" % (k + 1, len(faces))
    for i in range(len(boxes)):
        for j in range(i + 1, len(boxes)):
            bi, bj = boxes[i], boxes[j]
            gap = max(max(bi[0], bj[0]) - min(bi[2], bj[2]),
                      max(bi[1], bj[1]) - min(bi[3], bj[3]))
            assert gap >= 2.0 * a.margin - 1e-9, \
                   "islands %d and %d keep %g of canvas, under the %g gutter they paid" \
                   % (i + 1, j + 1, gap, 2.0 * a.margin)

    desc = ("profile " + ",".join("%g@%g" % t for t in rings) if a.profile is not None
            else "frustum r1=%g r2=%g h=%g"
                 % (rings[0][0], rings[-1][0], rings[-1][1] - rings[0][1]))
    out = ["# generated by gen_lathe.py (%s segs=%d caps=%s uvscale=%.6f)"
           % (desc, n, a.caps, scale),
           "o %s" % a.name]
    for v in verts:
        out.append("v %.6f %.6f %.6f" % v)
    for t in uvs:
        out.append("vt %.6f %.6f" % t)
    for v in normals:
        out.append("vn %.6f %.6f %.6f" % v)
    for k, face in enumerate(faces):
        out.append("f " + " ".join("%d/%d/%d" % (vi + 1, bases[k] + j + 1, k + 1)
                                   for j, vi in enumerate(face[0])))
    out.append("")
    with open(a.dst, "w") as fh:
        fh.write("\n".join(out))
    quads = sum(1 for f in faces if len(f[0]) == 4)
    tris = sum(1 for f in faces if len(f[0]) == 3)
    print("%s: %d verts, %d faces (%d wall quads + %d cone triangles + %d cap ngons), "
          "%d uv islands, uv scale %.4f"
          % (a.dst, len(verts), len(faces), quads, tris, len(faces) - quads - tris,
             len(faces), scale))


if __name__ == "__main__":
    main()
