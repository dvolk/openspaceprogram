#!/usr/bin/env python3
"""Generate the rocket landing-leg .obj: a footpad at the origin, a strut
leaning --splay degrees toward -X up to a mount plate at --drop height. The
part frame is the one Vehicle::applyGroundForces' leg loop assumes: origin at
the footpad centre, +Z up (parallel to the tank axis when mounted), plate
thin along X with its hull-side face carrying the surface node (parts.json
"nodes"). The splay is baked into the mesh because surface mating keeps the
child's +Z along the parent's stack axis (shipdef.cpp surfaceMatingRot).
"""
import argparse

import numpy as np
import trimesh

from flatten_normals import flatten
from gen_out import add_args, ship


def main():
    ap = argparse.ArgumentParser(
        description="Generate res/meshes/leg.obj (this module's header has the part frame)")
    ap.add_argument("--drop", type=float, default=2.6,
                    help="vertical foot-to-plate distance (m)")
    ap.add_argument("--splay", type=float, default=20.0,
                    help="outward lean from vertical (deg)")
    ap.add_argument("--pad-radius", type=float, default=0.3, help="footpad radius (m)")
    ap.add_argument("--pad-thick", type=float, default=0.1, help="footpad thickness (m)")
    ap.add_argument("--plate", type=float, default=0.3, help="mount plate face size (m)")
    ap.add_argument("--plate-thick", type=float, default=0.08,
                    help="mount plate thickness along X (m)")
    ap.add_argument("--strut", type=float, default=0.1, help="strut box section (m)")
    add_args(ap)
    a = ap.parse_args()

    s = a.drop * np.tan(np.radians(a.splay))   # horizontal foot->plate offset
    # Footpad: flat cylinder centred at the origin; contact face at -thick/2.
    pad = trimesh.creation.cylinder(radius=a.pad_radius, height=a.pad_thick, sections=24)
    # Strut: box from the foot to the plate centre, leaned toward -X.
    strut = trimesh.creation.box(extents=[a.strut, a.strut, np.hypot(s, a.drop)])
    strut.apply_transform(trimesh.transformations.rotation_matrix(
        -np.radians(a.splay), [0, 1, 0]))
    strut.apply_translation([-s / 2.0, 0, a.drop / 2.0])
    # Mount plate: thin along X; its hull-side face is the surface node.
    plate = trimesh.creation.box(extents=[a.plate_thick, a.plate, a.plate])
    plate.apply_translation([-s, 0, a.drop])
    leg = trimesh.util.concatenate([pad, strut, plate])
    dst = ship(a.out, "meshes", "leg.obj", force=a.force)
    # trimesh writes area-weighted corner normals, which shades a strut and two plates as
    # one rounded lump. flatten() gives every face its own normal (#1178) and copies the
    # positions through verbatim, so the contact point and the splay do not move.
    body, _ = flatten(leg.export(file_type="obj", include_normals=True))
    # Provenance header for utils/art/check_mesh_pins.py (trimesh writes none).
    with open(dst, "w") as f:
        f.write("# generated by gen_leg.py (drop=%.6g splay=%.6g pad r=%.6g t=%.6g "
                "plate=%.6g t=%.6g strut=%.6g)\n"
                % (a.drop, a.splay, a.pad_radius, a.pad_thick,
                   a.plate, a.plate_thick, a.strut))
        f.write(body)
    print("%s: drop=%.2f splay=%.1fdeg, srf node (%.3f, 0, %.2f), extents %s"
          % (dst, a.drop, a.splay, -(s + a.plate_thick / 2.0), a.drop,
             np.round(leg.extents, 3)))


if __name__ == "__main__":
    main()
