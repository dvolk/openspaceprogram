#!/usr/bin/env python3
"""Generate res/meshes/ladder.obj + res/textures/ladder.png: the EVA ladder,
a long box (v1 art; reports/ladders2026_11_21). Part frame: +Z = the long
(climb) axis, X = thickness with the hull-side face at -X (the surface node
in parts.json sits there, anchored at its TOP end -- #1078), Y = width.
Centred on the origin, so the standard mesh-box pins apply. The climb segment
parts.json authors rides the +X face.
Flat per-face normals, CCW winding -- the gen_fuselage.py conventions.
Size variants (#1078): --length <L> --name ladder_<L>m writes only
meshes/<name>.obj -- the grey texture is shared with the base part."""

import argparse
import os

from gen_out import add_args, ship


LADDER_RGB = (150, 152, 158)   # neutral grey, distinct from the tank skin


def box_faces(hx, hy, hz):
    """(normal, 4 CCW corners) per face, seen from outside."""
    return [
        ((1, 0, 0), [(hx, -hy, -hz), (hx, hy, -hz), (hx, hy, hz), (hx, -hy, hz)]),
        ((-1, 0, 0), [(-hx, -hy, -hz), (-hx, -hy, hz), (-hx, hy, hz), (-hx, hy, -hz)]),
        ((0, 1, 0), [(-hx, hy, -hz), (-hx, hy, hz), (hx, hy, hz), (hx, hy, -hz)]),
        ((0, -1, 0), [(-hx, -hy, -hz), (hx, -hy, -hz), (hx, -hy, hz), (-hx, -hy, hz)]),
        ((0, 0, 1), [(-hx, -hy, hz), (hx, -hy, hz), (hx, hy, hz), (-hx, hy, hz)]),
        ((0, 0, -1), [(-hx, -hy, -hz), (-hx, hy, -hz), (hx, hy, -hz), (hx, -hy, -hz)]),
    ]


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--thick", type=float, default=0.1,
                    help="thickness along X, the mount depth (m)")
    ap.add_argument("--wide", type=float, default=0.4, help="width along Y (m)")
    ap.add_argument("--length", type=float, default=2.0,
                    help="climb length along Z (m)")
    ap.add_argument("--name", default="ladder",
                    help="asset base name under res/ (size variants: ladder_1m etc.)")
    add_args(ap)
    a = ap.parse_args()
    hx, hy, hz = a.thick / 2.0, a.wide / 2.0, a.length / 2.0

    obj_path = ship(a.out, "meshes", a.name + ".obj", force=a.force)
    with open(obj_path, "w") as f:
        f.write("# generated by gen_ladder.py (thick=%.6g wide=%.6g length=%.6g)\n"
                % (a.thick, a.wide, a.length))
        verts, norms, faces = [], [], []
        for n, corners in box_faces(hx, hy, hz):
            base = len(verts)
            verts.extend(corners)
            norms.extend([n] * 4)
            faces.append((base, base + 1, base + 2))
            faces.append((base, base + 2, base + 3))
        for v in verts:
            f.write("v %.8f %.8f %.8f\n" % v)
        for n in norms:
            f.write("vn %.6f %.6f %.6f\n" % n)
        for t in faces:
            f.write("f %d//%d %d//%d %d//%d\n" % (
                t[0] + 1, t[0] + 1, t[1] + 1, t[1] + 1, t[2] + 1, t[2] + 1))
    print("wrote %s (%gx%gx%g m, srf node (%.3g, 0, %.3g))"
          % (obj_path, a.thick, a.wide, a.length, -hx, hz))

    if a.name != "ladder":
        # size variants ride the base part's texture -- same flat grey (#1078).
        return
    from PIL import Image
    img = Image.new("RGB", (64, 64), LADDER_RGB)
    png_path = ship(a.out, "textures", "ladder.png", force=a.force)
    img.save(png_path)
    print("wrote %s" % png_path)


if __name__ == "__main__":
    main()
