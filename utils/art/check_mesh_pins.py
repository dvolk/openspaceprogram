def obj_corner(field, nv, nt, nn):
    """One `v[/vt[/vn]]` corner as (v, vt, vn) 1-based indices, None where the field
    leaves one out (`f 1 2 3`, `f 1//2`). Negative indices count from the end, which the
    spec allows and which only resolves once the file has been read. None if the corner
    does not parse or lands out of range -- reported rather than crashing, because this
    gate runs against generated text that a future generator may format differently."""
    out = []
    for k, part in enumerate(field.split("/")[:3]):
        if not part:
            out.append(None)
            continue
        try:
            i = int(part)
        except ValueError:
            return None
        size = (nv, nt, nn)[k]
        i = i if i > 0 else size + 1 + i
        if not 1 <= i <= size:
            return None
        out.append(i)
    while len(out) < 3:
        out.append(None)
    return out


def read_faces(path):
    """(verts, uvs, normals, faces, bad) straight off the text. Stdlib on purpose: the
    committed half of this gate runs on the lint runner, where neither Blender nor trimesh
    is available. Each face is (verts, uvs, normals) of 1-based indices, one per corner,
    None where the corner text leaves that field out (`f 1 2 3`, `f 1//2`). `bad` names the
    first thing that will not parse -- a malformed `v`/`vt`/`vn` line or a corner that will
    not resolve -- because every count below it is then a guess. A bad line is still counted,
    so the numbering of everything after it stays the one assimp would see."""
    vs, uvs, nvs, raw = [], [], [], []
    bad = None
    with open(path, encoding="utf-8", errors="replace") as fh:
        for ln in fh:
            for pfx, want, bank in (("v ", 3, vs), ("vt ", 2, uvs), ("vn ", 3, nvs)):
                if ln.startswith(pfx):
                    t = ln.split()
                    try:
                        vals = [float(x) for x in t[1:]]
                    except ValueError:
                        vals = []
                    if len(vals) < want:
                        if bad is None:
                            bad = "`%s` does not parse, so every count below is a guess" \
                                  % ln.strip()
                        bank.append(None)
                    else:
                        bank.append(tuple(vals[:want]))
                    break
            else:
                if ln.startswith("f "):
                    raw.append(ln.split()[1:])
    faces = []
    for fields in raw:
        corners = [obj_corner(x, len(vs), len(uvs), len(nvs)) for x in fields]
        if any(c is None or c[0] is None for c in corners):
            if bad is None:
                bad = "face `f %s` does not parse, so every count below is a guess" \
                      % " ".join(fields)
            continue
        faces.append(tuple(zip(*corners)))     # (verts, uvs, normals), one index per corner
    return vs, uvs, nvs, faces, bad


def topo_problems(path, want_faces, min_texels=TOPO_MIN_FACE_TEXELS):
    """Why this .obj would be hard to paint, or [] if it is paintable."""
    vs, uvs, nvs, faces, unparsable = read_faces(path)
    if unparsable:
        return [unparsable]
    bad = []

    # A triangle is the sign of a wall somebody triangulated: the strip then unwraps into
    # zig-zag slivers. A closed tip is not that. A cone fan -- n congruent triangles all
    # meeting at one vertex, the axis point -- is the honest primitive for a nose cap, and
    # gen_lathe.py gives each one an island congruent to itself. The tell is that a tip
    # carries three quarters of the mesh's triangle corners; a triangulated wall spreads
    # its corners along a row, so no corner of it holds that many of them.
    tri = [f for f in faces if len(f[0]) == 3]
    corners = {}
    for f in tri:
        for v in f[0]:
            corners[v] = corners.get(v, 0) + 1
    tip = max(4, 3 * len(tri) // 4)
    slivers = sum(1 for f in tri if not any(corners[v] >= tip for v in f[0]))
    if slivers:
        bad.append("%d triangles: the authored family is wall quads plus one ngon per "
                   "end, and a triangulated wall unwraps into zig-zag slivers" % slivers)
    if len(faces) != want_faces:
        bad.append("%d faces, expected %d" % (len(faces), want_faces))
    no_norm = sum(1 for f in faces if any(x is None for x in f[2]))
    if no_norm:
        bad.append("%d faces carry no normal at all, so they shade off the smoothing of "
                   "whatever they happen to touch" % no_norm)
    # By VALUE, not by index. A face whose corners name three different `vn` lines holding
    # the same unit vector is flat: decoupler_radial.obj, barometer.obj and the ladders are
    # all written that way, and an index compare calls every one of them mixed.
    # ST_SAME_VALUE_NORMAL is the control that keeps this true.
    mixed = sum(1 for f in faces if all(x is not None for x in f[2])
                and len({nvs[i - 1] for i in f[2]}) != 1)
    if mixed:
        bad.append("%d faces carry more than one normal, so a face's own flat shading "
                   "blends into whatever meets it" % mixed)
    # Winding, from the corner order alone: an edge two faces share has to run one way in
    # each of them. These meshes take their normal from the winding (one per face), so an
    # edge running the same way twice means one face is inside out and shades the inside of
    # the part. Every size rule here reads an inside-out cap as perfect, and so does the
    # engine, which is why the generator asserts the same thing at the source.
    dirs = {}
    for f in faces:
        vi = f[0]
        for j in range(len(vi)):
            a, b = vi[j], vi[j - 1]
            dirs.setdefault((a, b) if a < b else (b, a), []).append((a, b))
    flip = sum(1 for dd in dirs.values() if len(dd) == 2 and dd[0] == dd[1])
    if flip:
        bad.append("%d shared edges run the same way in both faces: one face of each pair "
                   "is inside out, so its normal shades the inside of the part" % flip)

    if any(x is None for f in faces for x in f[1]):
        bad.append("a face has no uv, so it has no canvas to paint on")
        return bad

    # UV islands: faces joined across an edge only when that edge carries the same UV
    # on both sides. A seam -- the same vertex at two different UVs -- breaks the join,
    # which is exactly what one-island-per-face means.
    parent = list(range(len(faces)))

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    by_edge = {}
    for k, f in enumerate(faces):
        vi = f[0]
        for j in range(len(vi)):
            a, b = vi[j], vi[j - 1]
            by_edge.setdefault((a, b) if a < b else (b, a), []).append((k, j))
    for sides in by_edge.values():
        if len(sides) != 2:
            continue
        (ka, ja), (kb, jb) = sides
        va, vb = faces[ka][0], faces[kb][0]
        ua, ub = faces[ka][1], faces[kb][1]
        # Consistently-wound neighbours run a shared edge opposite ways, so A's corner ja
        # and B's corner jb-1 sit on the same vertex, and A's ja-1 pairs with B's jb.
        # Compare the wrong corners and every mesh looks seamless.
        if va[ja] != vb[jb - 1] or va[ja - 1] != vb[jb]:
            continue
        if ua[ja] == ub[jb - 1] and ua[ja - 1] == ub[jb]:
            ra, rb = find(ka), find(kb)
            if ra != rb:
                parent[rb] = ra
    islands = {}
    for k in range(len(faces)):
        islands.setdefault(find(k), []).append(k)
    # No rule on how MANY islands a mesh has. The lathe family keeps one per face because
    # that is what makes its density exact by construction; the engine bodies join faces into
    # long patches on purpose (uv_smart_blender.py), which is the only way a ring around a
    # nozzle or a stripe down a chamber can be stroked in an image editor at all -- 130
    # separate quads cannot be painted, and the hand-authored parts were never laid out that
    # way either (capsule.obj: 3 islands across 34 faces). What still bites is the geometry of
    # the layout below: real area per face, inside the canvas, no island laid over another.
    groups = list(islands.values())

    small = []
    for f in faces:
        pts = [uvs[i - 1] for i in f[1]]
        a = 0.0
        for i in range(len(pts)):
            x1, y1 = pts[i]
            x2, y2 = pts[(i + 1) % len(pts)]
            a += x1 * y2 - x2 * y1
        small.append(abs(a) * 0.5)
    tex = [a * CANVAS_PX * CANVAS_PX for a in small]
    thin = [t for t in tex if t < min_texels]
    if thin:
        bad.append("%d faces address %.0f texels each (min %.0f): the texture is being "
                   "read as almost one colour whatever it holds"
                   % (len(thin), min(thin), min_texels))

    # Where the layout sits, not just how big it is. A generator that lays an island
    # out about its own centre instead of from its corner puts half of it at negative uv:
    # src/texture.cpp clamps, so the part paints in an edge colour that nobody painted,
    # and the other half can land on top of a neighbour's island. gen_lathe.py hit both
    # (a cap disc spanning u -0.27..0.29, a nose cap with 17 islands under its base disc)
    # while every size rule above stayed happy, which is why this check exists. The box is
    # the ISLAND's here: the gutter the sampler needs is between patches. ST_UNSEAMED is the
    # control -- two faces, one island, their boxes meeting exactly along the seam, clean.
    boxes = []
    for g in groups:
        xs = [uvs[i - 1][0] for k in g for i in faces[k][1]]
        ys = [uvs[i - 1][1] for k in g for i in faces[k][1]]
        boxes.append((min(xs), min(ys), max(xs), max(ys)))
    outside = [b for b in boxes if b[0] < -1e-6 or b[1] < -1e-6
               or b[2] > 1.0 + 1e-6 or b[3] > 1.0 + 1e-6]
    if outside:
        bad.append("%d islands lie partly outside the canvas, reaching u %.4f..%.4f "
                   "v %.4f..%.4f: the sampler clamps at 0 and 1, so what falls out there "
                   "paints as an edge colour of the texture"
                   % (len(outside), min(b[0] for b in outside), max(b[2] for b in outside),
                      min(b[1] for b in outside), max(b[3] for b in outside)))

    # Do two faces share uv area? By real polygon area, not by box: engine.obj's 130 faces
    # have 202 pairs whose corner boxes overlap and 0 pairs that actually overlap, because a
    # joined patch IS a set of faces whose boxes meet. No adjacency bookkeeping is needed --
    # stitched neighbours share exact uv coordinates, so their polygons meet along a line and
    # the clipped area is exactly 0.0 (measured: 188..204 box candidates per engine body, 0
    # with real area). A box scan cannot see the defect the rule is for either -- one face
    # folded on top of its own neighbour (ST_FOLDED): inside one island that face has a legal
    # normal, legal area, legal winding, and boxes that meet every neighbour's; only the shared
    # area says "paint here and change there". Zero-area faces (the #1173 collapse) share
    # nothing by this test, which is why the texel floor above is what reports them.
    polys = [[uvs[i - 1] for i in f[1]] for f in faces]
    fboxes = [(min(p[0] for p in q), min(p[1] for p in q),
               max(p[0] for p in q), max(p[1] for p in q)) for q in polys]
    over, worst = 0, 0.0
    for i in range(len(polys)):
        for j in range(i + 1, len(polys)):
            a, b = fboxes[i], fboxes[j]
            if (min(a[2], b[2]) - max(a[0], b[0]) <= 0.0
                    or min(a[3], b[3]) - max(a[1], b[1]) <= 0.0):
                continue       # boxes apart, so nothing can overlap: the cheap cut first
            ar = uv_overlap_area(polys[i], polys[j])
            if ar > UV_OVERLAP_MIN:
                over += 1
                worst = max(worst, ar)
    if over:
        bad.append("%d pairs of faces share uv area (worst %.4f of the canvas): paint one "
                   "patch and another face changes too, and the mip filter blends across it"
                   % (over, worst))
    return bad


